    /// The readings one by one, as [`Locating`] closes them: each fix of
    /// the refutation alone.
    #[test]
    fn figures_tracked_each_way_of_naming_a_tracked_function_reads_ue_21() {
        let close = |text: &str| {
            let mut locating = Locating::default();
            locating.read(&syn::parse_file(text).expect("parses"), "lib.rs", false);
            locating.close(&BTreeSet::new())
        };
        let reads = |text: &str, name: &str| close(text).reading.contains(name);
        let caller = "{ core::panic::Location::caller().column() }";
        assert!(reads(
            &format!("#[cfg_attr(test, track_caller)] fn a() -> u32 {caller}"),
            "a"
        ));
        assert!(reads(
            &format!(
                "#[cfg_attr(any(), inline, cfg_attr(all(), track_caller))] fn a() -> u32 {caller}"
            ),
            "a"
        ));
        // A tracked function whose location reaches only a panic reads no value.
        assert!(!reads(
            "#[track_caller] fn a(x: Option<u32>) -> u32 { x.unwrap() }",
            "a"
        ));
        // ... unless it calls one that reads, or a macro the figures do not read.
        assert!(reads(
            &format!(
                "#[track_caller] fn b() -> u32 {caller}\n#[track_caller] fn a() -> u32 {{ b() }}"
            ),
            "a"
        ));
        assert!(reads("#[track_caller] fn a() -> u32 { far::col!() }", "a"));
        assert!(reads(
            "trait T { #[track_caller] fn a(&self) -> u32; }",
            "a"
        ));
        // A macro writes the function: from its call, or a name in its body.
        let mk = "macro_rules! mk { ($n:ident) => { #[track_caller] pub fn $n() -> u32 { core::panic::Location::caller().column() } }; }\nmk!(made);";
        assert!(reads(mk, "made"));
        let fixed = "macro_rules! mk { () => { #[track_caller] pub fn fixed() -> u32 { core::panic::Location::caller().column() } }; }\nmk!();";
        assert!(reads(fixed, "fixed"));
        // Through a macro that only passes the attribute on.
        let pass = "macro_rules! item { ($i:item) => { $i }; }\nitem!(#[track_caller] fn inner() -> u32 { core::panic::Location::caller().column() });";
        assert!(reads(pass, "inner"));
        // A renamed one, twice.
        let renamed = format!("mod a {{ #[track_caller] pub fn l() -> u32 {caller} }}\npub use a::l as m;\nuse m as n;");
        assert!(reads(&renamed, "m") && reads(&renamed, "n"));
        // A metavariable names any macro.
        let meta = "macro_rules! call { ($vec:ident) => { $vec!() }; }";
        assert!(reads(meta, "call"));
        assert!(!reads("macro_rules! call { () => { vec![] }; }", "call"));
        // A dependency's macro reads by its call, never by an identifier
        // of its name; a tracked body calling it reads only if it reads.
        let mut locating = Locating::default();
        let dependency =
            "macro_rules! here { () => { column!() } }\nmacro_rules! still { () => { 1 } }";
        locating.read(
            &syn::parse_file(dependency).expect("parses"),
            "dep.rs",
            true,
        );
        let tracked = "#[track_caller] fn a() -> u32 { still!() }\n#[track_caller] fn b() -> u32 { here!() }\nfn c(here: u32) -> u32 { here }";
        locating.read(&syn::parse_file(tracked).expect("parses"), "lib.rs", false);
        let located = locating.close(&BTreeSet::new());
        assert_eq!(located.reading, ["b".to_string()].into());
        let (columns, _) = location_lines(tracked, &located);
        assert!(!columns.contains(&3), "{columns:?}");
        // What the source cannot show makes every call unknown.
        let under = format!("#[some::attribute] #[track_caller] fn a() -> u32 {caller}");
        assert!(close(&under).calls.is_some());
        let around =
            format!("#[some::attribute] impl S {{ #[track_caller] fn a() -> u32 {caller} }}");
        assert!(close(&around).calls.is_some());
        // A test attribute is the prelude's while the workspace binds no `test`.
        let test = "#[test] #[track_caller] fn t() { assert!(true) }";
        assert!(close(test).calls.is_none());
        let mut locating = Locating::default();
        locating.read(&syn::parse_file(test).expect("parses"), "lib.rs", false);
        assert!(locating.close(&["test".to_string()].into()).calls.is_some());
        let built = "macro_rules! mk { ($n:ident) => { other::paste! { #[track_caller] fn [<get_ $n>]() {} } }; }";
        assert!(close(built).calls.is_some());
        let proc = "fn f() { other::emit!(#[track_caller] fn g() {}); }";
        assert!(close(proc).calls.is_some());
        // A procedural macro crate that builds the attribute into its output.
        let emits = "macro_rules! quote { ($($t:tt)*) => { () }; }\nfn expand() { quote!(#[track_caller] fn made() {}) }";
        let mut locating = Locating::default();
        locating.read(&syn::parse_file(emits).expect("parses"), "gen.rs", true);
        assert!(locating.close(&BTreeSet::new()).calls.is_none());
        locating.generator = true;
        locating.read(&syn::parse_file(emits).expect("parses"), "gen.rs", true);
        assert!(locating.close(&BTreeSet::new()).calls.is_some());
        assert!(close(&format!("#[track_caller] fn a() -> u32 {caller}"))
            .calls
            .is_none());
    }

