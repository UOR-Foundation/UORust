    /// Rewrite `lib` in a workspace whose package `p` depends on the path
    /// crate `far` outside its directory (no member); each `(function, value)` is one figure.
    fn figures_tracked_rewrite(
        tag: &str,
        lib: &str,
        sites: &[(&str, &str)],
    ) -> (Rewritten, String) {
        let rows: Vec<(String, String, String)> = sites
            .iter()
            .map(|(f, v)| {
                (
                    format!("the_figure_of_{f}"),
                    (*v).to_string(),
                    format!("\"p/p::{f}:{v}:0\""),
                )
            })
            .collect();
        let rows: Vec<(&str, &str, &str)> = rows
            .iter()
            .map(|(a, b, c)| (a.as_str(), b.as_str(), c.as_str()))
            .collect();
        let dir = figures_repair_workspace(
            tag,
            &[
                ("ws/Cargo.toml", FIGURES_REPAIR_ROOT),
                ("ws/Cargo.lock", FIGURES_TRACKED_LOCK),
                (
                    "ws/p/Cargo.toml",
                    &figures_repair_manifest(
                        "figs = { path = \"../figs\" }\nfar = { path = \"../../far\" }\n",
                    ),
                ),
                ("ws/p/src/lib.rs", lib),
                (
                    "far/Cargo.toml",
                    "[package]\nname = \"far\"\nversion = \"0.1.0\"\nedition = \"2021\"\n",
                ),
                ("far/src/lib.rs", FIGURES_TRACKED_FAR),
                ("ws/figs/Cargo.toml", FIGURES_REPAIR_FIGS),
                ("ws/figs/src/lib.rs", "#![no_std]\n"),
                ("ws/rules.toml", FIGURES_REPAIR_RULES),
                ("ws/figures.toml", &figures_repair_figure_rows(&rows)),
            ],
        );
        let ws = dir.join("ws");
        let done =
            rewrite(&ws, &ws.join("rules.toml"), &ws.join("figures.toml")).expect("rewritten");
        let after = std::fs::read_to_string(ws.join("p/src/lib.rs")).expect("read");
        let _ = std::fs::remove_dir_all(&dir);
        (done, after)
    }

