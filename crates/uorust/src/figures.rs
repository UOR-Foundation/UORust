//! Figures: every numeric literal of a workspace gets a home in the model
//! (UE-21).
//!
//! This is not translation. It reads a workspace with the tool's own source
//! reader ([`crate::ingest::workspace`], then `syn` with spans), and keeps a
//! figure register: one row per numeric-literal site and one row per figure,
//! a named value with the kind of home the model gives it. Four steps use the
//! register:
//!
//! - [`extract`] writes the register from the workspace. It keeps the figure
//!   rows a register already holds and re-reads every site, so a site whose
//!   key no figure lists is a row that says it has no figure: the command
//!   never invents a meaning for a number.
//! - [`write`] generates the package the workspace's packages depend on: one
//!   exported macro per figure that expands to the literal token exactly as
//!   the register states it, so type inference, constant evaluation and the
//!   value of every expression are what they were (a macro expands to the
//!   token before either runs), and a typed constant only where Rust needs a
//!   path (a range-pattern bound). It also writes the LexLean module that
//!   states the same figures, since the register is the one statement of
//!   each value (the SDK writes no Rust literal from a LexLean definition).
//! - [`rewrite`] replaces each site that has a figure by the generated name,
//!   and refuses with a typed row each site it cannot place soundly.
//! - [`check`] is the gate: no counted site lacks a figure, every figure
//!   states its home, the register and the generated files are current, and
//!   the count of figures whose home names no check is reported, so that no
//!   free literal cannot be reached by renaming alone.
//!
//! Which literals are exempt and which paths are which stratum is an input,
//! the rule file ([`Rules`]), never a table here.

