/// One figure: a named value and its home in the model.
#[derive(Clone, Debug, Default, Deserialize, PartialEq, Eq)]
#[serde(deny_unknown_fields)]
pub struct Figure {
    /// Its name: a lowercase Rust identifier, the generated macro's name.
    pub name: String,
    /// The literal token exactly as the sites write it, suffix included.
    pub value: String,
    /// The kind of its home: `authority`, `parameter`, `derived` or
    /// `definition`; empty while it has none.
    #[serde(default)]
    pub home: String,
    /// What the home cites: the authority and clause, the law that bounds
    /// the parameter, the derivation, or the operation it is part of.
    #[serde(default)]
    pub cites: String,
    /// The check that establishes the home (an ID whose test holds it);
    /// empty while none does.
    #[serde(default)]
    pub check: String,
    /// The Rust type of the typed constant a range-pattern bound needs, when
    /// the value has no suffix to state it.
    #[serde(default, rename = "type")]
    pub ty: String,
    /// The keys of its sites.
    #[serde(default)]
    pub sites: Vec<String>,
}

