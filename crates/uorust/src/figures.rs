/// What a register says about itself: its counts.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct Counts {
    /// Counted sites.
    pub sites: usize,
    /// Counted sites no figure lists.
    pub free: usize,
    /// Counted sites a figure lists.
    pub figured: usize,
    /// Sites written as a generated name.
    pub rewritten: usize,
    /// Sites no rewrite can place, by reason.
    pub refusals: BTreeMap<String, usize>,
    /// Figures.
    pub figures: usize,
    /// Figures that state no home.
    pub unhomed: usize,
    /// Figures whose home names no check.
    pub unchecked: usize,
}

/// Whether a figure states its home: one of [`HOMES`], citing something.
fn homed(f: &Figure) -> bool {
    HOMES.contains(&f.home.trim()) && !f.cites.trim().is_empty()
}

/// Whether a figure's home names a check.
fn checked(f: &Figure) -> bool {
    !f.check.trim().is_empty()
}

impl Register {
    /// Its counts.
    pub fn counts(&self) -> Counts {
        let listed = self.listed();
        let mut c = Counts {
            sites: self.sites.len(),
            figures: self.figures.len(),
            ..Counts::default()
        };
        for site in &self.sites {
            if listed.contains_key(site.key.as_str()) {
                c.figured += 1;
            } else {
                c.free += 1;
            }
            if site.form != Form::Literal {
                c.rewritten += 1;
            }
            if let Some(why) = site.place.refusal() {
                *c.refusals.entry(why.to_string()).or_default() += 1;
            }
        }
        c.unhomed = self.figures.iter().filter(|f| !homed(f)).count();
        c.unchecked = self.figures.iter().filter(|f| !checked(f)).count();
        c
    }

    /// Each listed site key, with the figure that lists it.
    fn listed(&self) -> BTreeMap<&str, &Figure> {
        self.figures
            .iter()
            .flat_map(|f| f.sites.iter().map(move |k| (k.as_str(), f)))
            .collect()
    }

    /// The register file, the same bytes for the same register.
    pub fn render(&self, rules_digest: &str) -> String {
        let c = self.counts();
        let mut out = String::new();
        let _ = writeln!(
            out,
            "# Honesty report: {} counted numeric-literal sites, {} with a figure, {} without \
             one; {} written as a generated name.",
            c.sites, c.figured, c.free, c.rewritten
        );
        let _ = writeln!(
            out,
            "# {} figures, {} stating no home, {} whose home names no check.",
            c.figures, c.unhomed, c.unchecked
        );
        for (why, n) in &c.refusals {
            let _ = writeln!(out, "# {n} sites no rewrite can place: {why}.");
        }
        let _ = writeln!(out, "spec = {}", quote(REGISTER_SPEC));
        let _ = writeln!(out, "rules = {}", quote(rules_digest));
        let _ = writeln!(out, "figures = {}", quote(&self.figures_digest()));
        let list = |items: &[String]| {
            let quoted: Vec<String> = items.iter().map(|s| quote(s)).collect();
            format!("[{}]", quoted.join(", "))
        };
        let _ = writeln!(out, "unstratified = {}", list(&self.unstratified));
        let _ = writeln!(out, "unparsed = {}", list(&self.unparsed));
        let _ = writeln!(out, "unread = {}", list(&self.unread));
        for f in &self.figures {
            out.push_str("\n[[figure]]\n");
            let _ = writeln!(out, "name = {}", quote(&f.name));
            let _ = writeln!(out, "value = {}", quote(&f.value));
            let _ = writeln!(out, "home = {}", quote(&f.home));
            let _ = writeln!(out, "cites = {}", quote(&f.cites));
            let _ = writeln!(out, "check = {}", quote(&f.check));
            if !f.ty.is_empty() {
                let _ = writeln!(out, "type = {}", quote(&f.ty));
            }
            let _ = writeln!(out, "sites = {}", list(&f.sites));
        }
        let listed = self.listed();
        for s in &self.sites {
            out.push_str("\n[[site]]\n");
            let _ = writeln!(out, "key = {}", quote(&s.key));
            let _ = writeln!(out, "file = {}", quote(&s.file));
            let _ = writeln!(
                out,
                "span = [{}, {}, {}, {}]",
                s.start.0, s.start.1, s.end.0, s.end.1
            );
            let _ = writeln!(out, "literal = {}", quote(&s.literal));
            let _ = writeln!(out, "place = {}", quote(s.place.name()));
            let _ = writeln!(
                out,
                "stratum = {}",
                quote(s.stratum.as_deref().unwrap_or(""))
            );
            if s.test {
                out.push_str("test = true\n");
            }
            let form = match &s.form {
                Form::Literal => "literal",
                Form::Macro(_) => "macro",
                Form::Constant(_) => "constant",
            };
            let _ = writeln!(out, "form = {}", quote(form));
            // Derived from the figure rows, which are the statement: a site
            // no figure lists says so.
            let figure = listed.get(s.key.as_str()).map_or("", |f| f.name.as_str());
            let _ = writeln!(out, "figure = {}", quote(figure));
            if let Some(why) = s.place.refusal() {
                let _ = writeln!(out, "refusal = {}", quote(why));
            }
        }
        out
    }

    /// The SHA-256 of the figure rows' values and homes, which is all the
    /// generated files depend on.
    pub fn figures_digest(&self) -> String {
        let mut text = String::new();
        for f in &self.figures {
            let _ = writeln!(
                text,
                "{}\u{0}{}\u{0}{}\u{0}{}\u{0}{}\u{0}{}",
                f.name, f.value, f.home, f.cites, f.check, f.ty
            );
        }
        hex(&Sha256::digest(text.as_bytes()))
    }
}

/// TOML's basic string of a text.
fn quote(s: &str) -> String {
    toml::Value::String(s.to_string()).to_string()
}

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

fn malformed(path: &Path, reason: impl ToString) -> UorustError {
    UorustError::Malformed {
        path: path.to_path_buf(),
        reason: reason.to_string(),
    }
}

/// Read a rule file.
pub fn read_rules(path: &Path) -> Result<(Rules, String), UorustError> {
    let text = std::fs::read_to_string(path).map_err(|e| io(path, e))?;
    let rules: Rules = toml::from_str(&text).map_err(|e| malformed(path, e))?;
    if rules.spec != RULES_SPEC {
        return Err(malformed(path, format!("spec is not {RULES_SPEC}")));
    }
    if !is_name(&rules.package.name.replace('-', "_")) {
        return Err(malformed(path, "the package name is no crate name"));
    }
    for value in &rules.exempt {
        if value_of(value).is_none() {
            return Err(malformed(path, format!("{value} is no numeric literal")));
        }
    }
    Ok((rules, hex(&Sha256::digest(text.as_bytes()))))
}

/// The figure rows of a register file; none when it does not exist.
pub fn read_figures(path: &Path) -> Result<Vec<Figure>, UorustError> {
    #[derive(Deserialize)]
    struct File {
        spec: String,
        #[serde(default)]
        figure: Vec<Figure>,
    }
    if !path.exists() {
        return Ok(Vec::new());
    }
    let text = std::fs::read_to_string(path).map_err(|e| io(path, e))?;
    // The site rows are output, re-derived on every read: only the figure
    // rows are the register's statement.
    let value: toml::Value = text.parse().map_err(|e| malformed(path, e))?;
    let mut table = value
        .as_table()
        .cloned()
        .ok_or_else(|| malformed(path, "not a table"))?;
    table.retain(|k, _| k == "spec" || k == "figure");
    let file: File = toml::Value::Table(table)
        .try_into()
        .map_err(|e| malformed(path, e))?;
    if file.spec != REGISTER_SPEC {
        return Err(malformed(path, format!("spec is not {REGISTER_SPEC}")));
    }
    let mut names = BTreeSet::new();
    let mut keys = BTreeSet::new();
    for f in &file.figure {
        if !is_name(&f.name) || f.name.chars().any(|c| c.is_ascii_uppercase()) {
            return Err(malformed(
                path,
                format!("{} is no lowercase identifier", f.name),
            ));
        }
        if !names.insert(f.name.as_str()) {
            return Err(malformed(
                path,
                format!("the figure {} is stated twice", f.name),
            ));
        }
        if value_of(&f.value).is_none() {
            return Err(malformed(
                path,
                format!("{} is no numeric literal", f.value),
            ));
        }
        for k in &f.sites {
            if !keys.insert(k.as_str()) {
                return Err(malformed(path, format!("the site {k} is listed twice")));
            }
        }
    }
    // The LexLean module states each figure under names made from its own;
    // two figures must not make one name.
    let mut lexlean: BTreeMap<String, &str> = BTreeMap::new();
    for f in &file.figure {
        for n in lexlean_names(f) {
            if let Some(other) = lexlean.insert(n.clone(), &f.name) {
                return Err(malformed(
                    path,
                    format!(
                        "the figures {other} and {} both state the LexLean definition {n}",
                        f.name
                    ),
                ));
            }
        }
    }
    Ok(file.figure)
}

/// The names of a figure's LexLean definitions: `figure_<name>` for an
/// integer, `figure_<name>_significand` and `figure_<name>_exponent` for a
/// float (see [`lexlean_module`]).
fn lexlean_names(f: &Figure) -> Vec<String> {
    let base = format!("figure_{}", f.name);
    match value_of(&f.value) {
        Some(Value::Int(_)) => vec![base],
        Some(Value::Float(_)) => vec![format!("{base}_significand"), format!("{base}_exponent")],
        None => Vec::new(),
    }
}

/// Whether a text is a Rust identifier no keyword spells.
fn is_name(s: &str) -> bool {
    syn::parse_str::<syn::Ident>(s).is_ok()
}

/// A numeric literal's value.
#[derive(Clone, Copy, Debug, PartialEq)]
enum Value {
    Int(u128),
    Float(f64),
}

/// The value of a literal token, when it is a numeric one.
fn value_of(text: &str) -> Option<Value> {
    match syn::parse_str::<syn::Lit>(text).ok()? {
        syn::Lit::Int(i) => i.base10_parse::<u128>().ok().map(Value::Int),
        syn::Lit::Float(f) => f.base10_parse::<f64>().ok().map(Value::Float),
        _ => None,
    }
}

/// Whether a literal's value is one the rules exempt: equal as numbers,
/// so `1.0` is exempt where `1` is.
fn exempt(literal: &str, rules: &Rules) -> bool {
    let Some(v) = value_of(literal) else {
        return false;
    };
    let as_float = |v: Value| match v {
        Value::Int(i) => i as f64,
        Value::Float(f) => f,
    };
    rules
        .exempt
        .iter()
        .filter_map(|e| value_of(e))
        .any(|e| match (v, e) {
            (Value::Int(a), Value::Int(b)) => a == b,
            (a, b) => as_float(a) == as_float(b),
        })
}

/// The stratum of a file: the one with the longest prefix naming it.
fn stratum_of<'r>(file: &str, rules: &'r Rules) -> Option<&'r Stratum> {
    rules
        .stratum
        .iter()
        .flat_map(|s| s.paths.iter().map(move |p| (p, s)))
        .filter(|(p, _)| file.starts_with(p.as_str()))
        .max_by_key(|(p, _)| p.len())
        .map(|(_, s)| s)
}

/// Byte offsets of line starts, to turn a span's line and column into bytes.
struct Lines<'t> {
    text: &'t str,
    starts: Vec<usize>,
}

impl<'t> Lines<'t> {
    fn new(text: &'t str) -> Self {
        let mut starts = vec![0];
        starts.extend(text.match_indices('\n').map(|(i, _)| i + 1));
        Self { text, starts }
    }

    /// The byte of a line (1-based) and column (characters).
    fn byte(&self, at: LineColumn) -> usize {
        let start = self
            .starts
            .get(at.line.saturating_sub(1))
            .copied()
            .unwrap_or(self.text.len());
        let rest = &self.text[start..];
        rest.char_indices()
            .nth(at.column)
            .map_or(self.text.len(), |(i, _)| start + i)
    }

    /// The line and column of a byte.
    fn at(&self, byte: usize) -> LineColumn {
        let line = self.starts.partition_point(|s| *s <= byte);
        let start = self.starts[line - 1];
        LineColumn {
            line,
            column: self.text[start..byte].chars().count(),
        }
    }
}

/// A site as the walk meets it, before its key is known.
struct Raw {
    item: String,
    literal: String,
    place: Place,
    test: bool,
    form: Form,
    bytes: (usize, usize),
}

/// The walk over one file's syntax.
struct Walk<'a> {
    lines: &'a Lines<'a>,
    /// The names the file's package binds the generated package under.
    krates: &'a BTreeSet<String>,
    /// The value of each figure, to read a rewritten site's literal.
    figures: &'a BTreeMap<String, String>,
    /// Macro names the workspace defines or imports.
    shadowed: &'a BTreeSet<String>,
    /// The package's edition.
    edition: &'a str,
    /// Whether rustdoc tests the file's doc comments (a library target).
    doctested: bool,
    items: Vec<String>,
    test: bool,
    /// A place every literal under it takes, whatever its parent.
    frozen: Option<Place>,
    raws: Vec<Raw>,
    /// Doc text read from another file (`#[doc = include_str!(..)]`): the
    /// path as written, and the item it documents.
    included: Vec<(String, String)>,
    /// What the walk could not read, each a reason.
    unread: Vec<String>,
}

impl Walk<'_> {
    fn record_bytes(&mut self, bytes: (usize, usize), literal: String, place: Place, form: Form) {
        let place = self.frozen.unwrap_or(place);
        self.raws.push(Raw {
            item: self.items.join("::"),
            literal,
            place,
            test: self.test,
            form,
            bytes,
        });
    }

    fn record(&mut self, span: proc_macro2::Span, literal: String, place: Place) {
        let bytes = (self.lines.byte(span.start()), self.lines.byte(span.end()));
        self.record_bytes(bytes, literal, place, Form::Literal);
    }

    /// A numeric literal, recorded at its place.
    fn lit(&mut self, lit: &syn::Lit, place: Place) -> bool {
        match lit {
            syn::Lit::Int(_) | syn::Lit::Float(_) => {
                let text = lit.to_token_stream_text();
                let start = self.lines.byte(lit.span().start());
                let end = self.lines.byte(lit.span().end());
                // A literal pattern's sign is part of the pattern: the
                // literal is the digits after it.
                match text.strip_prefix('-') {
                    Some(digits) => {
                        let digits = digits.trim_start().to_string();
                        let from = end.saturating_sub(digits.len()).max(start);
                        self.record_bytes(
                            (from, end),
                            digits,
                            Place::NegativePattern,
                            Form::Literal,
                        );
                    }
                    None => self.record_bytes((start, end), text, place, Form::Literal),
                }
                true
            }
            _ => false,
        }
    }

    /// An expression whose own literal takes `place`.
    fn child(&mut self, e: &syn::Expr, place: Place) {
        match e {
            syn::Expr::Lit(l) if l.attrs.is_empty() => {
                if !self.lit(&l.lit, place) {
                    self.visit_expr(e);
                }
            }
            syn::Expr::Unary(u) if matches!(u.op, syn::UnOp::Neg(_)) => match &*u.expr {
                syn::Expr::Lit(l) if place != Place::ConstGeneric => {
                    if !self.lit(&l.lit, place) {
                        self.visit_expr(e);
                    }
                }
                _ => self.visit_expr(e),
            },
            _ => self.visit_expr(e),
        }
    }

    /// Under an item of the given name (none for a block that is no path
    /// scope, such as an `extern` block), test code when its attributes say
    /// so, and the macro's tokens when an attribute is a macro. Every item
    /// kind that carries attributes is visited through here.
    fn scoped(
        &mut self,
        attrs: &[syn::Attribute],
        name: Option<String>,
        f: impl FnOnce(&mut Self),
    ) {
        let test = self.test;
        let frozen = self.frozen;
        self.test |= crate::ingest::test_only(attrs);
        let named = name.is_some();
        if let Some(name) = name {
            self.items.push(name);
        }
        for a in attrs {
            self.visit_attribute(a);
        }
        self.docs(attrs);
        if attrs
            .iter()
            .any(|a| matches!(a.style, syn::AttrStyle::Outer) && !builtin(&a.meta, self.shadowed))
        {
            self.frozen = Some(Place::MacroTokens);
        }
        f(self);
        if named {
            self.items.pop();
        }
        self.test = test;
        self.frozen = frozen;
    }

    /// The doc tests of an item's doc attributes: rustdoc compiles the Rust
    /// code blocks of a library's docs as tests, so their literals are
    /// sites of test code, which no rewrite places. A doc comment's text is
    /// its source's bytes after `///`, `//!`, `/**` or `/*!`, or inside the
    /// quotes of `#[doc = "..."]`; text read from a file
    /// (`#[doc = include_str!("..")]`) is read there; any other doc text (an
    /// escape, a computed value) is a row of what could not be read.
    fn docs(&mut self, attrs: &[syn::Attribute]) {
        if !self.doctested {
            return;
        }
        let item = self.items.join("::");
        let mut lines: Vec<(String, usize)> = Vec::new();
        for a in attrs {
            if !a.path().is_ident("doc") {
                continue;
            }
            let syn::Meta::NameValue(nv) = &a.meta else {
                continue;
            };
            match &nv.value {
                syn::Expr::Lit(syn::ExprLit {
                    lit: syn::Lit::Str(s),
                    ..
                }) => {
                    let value = s.value();
                    let start = self.lines.byte(s.span().start());
                    let end = self.lines.byte(s.span().end()).max(start);
                    let src = &self.lines.text[start..end];
                    let at = if ["///", "//!", "/**", "/*!"]
                        .iter()
                        .any(|p| src.starts_with(p))
                    {
                        Some(start + 3)
                    } else {
                        src.find('"').map(|q| start + q + 1)
                    };
                    let text = self.lines.text;
                    match at.filter(|o| text.get(*o..*o + value.len()) == Some(value.as_str())) {
                        Some(o) => lines.extend(lines_at(&value, o)),
                        None => self.unread.push(format!(
                            "{item}: a doc comment whose text is not spelled as written"
                        )),
                    }
                }
                syn::Expr::Macro(m) if m.mac.path.is_ident("include_str") => {
                    match m.mac.parse_body::<syn::LitStr>() {
                        Ok(p) => self.included.push((p.value(), item.clone())),
                        Err(_) => self
                            .unread
                            .push(format!("{item}: a doc text included from no literal path")),
                    }
                }
                _ => self
                    .unread
                    .push(format!("{item}: a doc attribute whose text is computed")),
            }
        }
        let (found, unlexed) = doc_literals(&lines);
        for (a, b, literal) in found {
            self.raws.push(Raw {
                item: item.clone(),
                literal,
                place: Place::DocTest,
                test: true,
                form: Form::Literal,
                bytes: (a, b),
            });
        }
        for at in unlexed {
            let line = self.lines.at(at).line;
            self.unread
                .push(format!("{item}: the doc test at line {line} does not lex"));
        }
    }

    /// Every numeric literal of a token tree, at `place`.
    fn tokens(&mut self, tokens: &TokenStream, place: Place) {
        for (span, text) in numeric_tokens(tokens) {
            self.record(span, text, place);
        }
    }

    /// A rewritten site: `::<crate>::<figure>!()` with no arguments.
    fn generated_macro(&self, m: &syn::Macro) -> Option<String> {
        let segs: Vec<String> = m
            .path
            .segments
            .iter()
            .map(|s| s.ident.to_string())
            .collect();
        match segs.as_slice() {
            [k, name] if self.krates.contains(k) && m.tokens.is_empty() => Some(name.clone()),
            _ => None,
        }
    }

    /// The standard macro a path names, when it names one this walk knows:
    /// one segment, or `std`/`core`/`alloc` and the name, and not a name the
    /// workspace binds to a macro of its own.
    fn standard(&self, path: &syn::Path) -> Option<String> {
        standard_macro(path, self.shadowed)
    }

    fn mac(&mut self, m: &syn::Macro, whole: (usize, usize)) {
        if let Some(name) = self.generated_macro(m) {
            let literal = self.figures.get(&name).cloned().unwrap_or_default();
            self.record_bytes(whole, literal, Place::Expression, Form::Macro(name));
            return;
        }
        if m.path.is_ident("macro_rules") {
            self.tokens(&m.tokens, Place::MacroRules);
            return;
        }
        let Some(name) = self.standard(&m.path) else {
            self.tokens(&m.tokens, Place::MacroTokens);
            self.nested_format_specs(&m.tokens);
            return;
        };
        if !self.standard_args(&name, m) {
            self.tokens(&m.tokens, Place::MacroTokens);
            self.nested_format_specs(&m.tokens);
        }
    }

    /// The format specs of a standard formatting macro written inside the
    /// tokens of another macro (`outer!(format!("{:04}", y))`): the width,
    /// precision or index is a number the source spells, so it is a site
    /// at its place, though no rewrite places a format spec. The macro
    /// around it decides what its tokens mean, so nothing else of them is
    /// read by the standard grammar.
    fn nested_format_specs(&mut self, tokens: &TokenStream) {
        use syn::parse::Parser;
        let tokens: Vec<TokenTree> = tokens.clone().into_iter().collect();
        for (i, t) in tokens.iter().enumerate() {
            let TokenTree::Group(g) = t else {
                continue;
            };
            let call = match (
                i.checked_sub(2).map(|k| &tokens[k]),
                i.checked_sub(1).map(|k| &tokens[k]),
            ) {
                (Some(TokenTree::Ident(id)), Some(TokenTree::Punct(p))) if p.as_char() == '!' => {
                    let segments = if i >= 5
                        && matches!(&tokens[i - 3], TokenTree::Punct(p) if p.as_char() == ':')
                        && matches!(&tokens[i - 4], TokenTree::Punct(p) if p.as_char() == ':')
                    {
                        match &tokens[i - 5] {
                            TokenTree::Ident(root) => vec![root.to_string(), id.to_string()],
                            _ => vec![String::new(), id.to_string()],
                        }
                    } else {
                        vec![id.to_string()]
                    };
                    let path: syn::Path = match syn::parse_str(&segments.join("::")) {
                        Ok(path) => path,
                        Err(_) => syn::Path::from(id.clone()),
                    };
                    self.standard(&path).and_then(|name| format_position(&name))
                }
                _ => None,
            };
            // The tokens `stringify!` is given are text, not a program.
            let stringified = i >= 2
                && matches!(&tokens[i - 1], TokenTree::Punct(p) if p.as_char() == '!')
                && matches!(&tokens[i - 2], TokenTree::Ident(id) if id == "stringify")
                && !self.shadowed.contains("stringify")
                && match i.checked_sub(5).map(|k| (&tokens[k], &tokens[k + 1])) {
                    Some((TokenTree::Ident(root), TokenTree::Punct(c))) if c.as_char() == ':' => {
                        root == "std" || root == "core"
                    }
                    _ => {
                        !(i >= 3
                            && matches!(&tokens[i - 3], TokenTree::Punct(c) if c.as_char() == ':'))
                    }
                };
            if stringified {
                continue;
            }
            let Some(at) = call else {
                self.nested_format_specs(&g.stream());
                continue;
            };
            let parsed =
                Punctuated::<syn::Expr, syn::Token![,]>::parse_terminated.parse2(g.stream());
            if let Some(syn::Expr::Lit(syn::ExprLit {
                lit: syn::Lit::Str(s),
                ..
            })) = parsed.ok().and_then(|args| args.into_iter().nth(at))
            {
                self.format_spec(&s);
            }
            self.nested_format_specs(&g.stream());
        }
    }

    /// The arguments of a standard macro, by its grammar; `false` when they
    /// do not parse by it.
    fn standard_args(&mut self, name: &str, m: &syn::Macro) -> bool {
        use syn::parse::Parser;
        if name == "matches" {
            let parser = |input: syn::parse::ParseStream| {
                let e: syn::Expr = input.parse()?;
                let _: syn::Token![,] = input.parse()?;
                let p = syn::Pat::parse_multi_with_leading_vert(input)?;
                let guard = if input.peek(syn::Token![if]) {
                    let _: syn::Token![if] = input.parse()?;
                    Some(input.parse::<syn::Expr>()?)
                } else {
                    None
                };
                let _: Option<syn::Token![,]> = input.parse()?;
                Ok((e, p, guard))
            };
            let Ok((e, p, guard)) = parser.parse2(m.tokens.clone()) else {
                return false;
            };
            self.child(&e, Place::MacroArgument);
            self.visit_pat(&p);
            if let Some(g) = guard {
                self.child(&g, Place::MacroArgument);
            }
            return true;
        }
        if name == "vec" {
            let repeat = |input: syn::parse::ParseStream| {
                let e: syn::Expr = input.parse()?;
                let _: syn::Token![;] = input.parse()?;
                let n: syn::Expr = input.parse()?;
                Ok((e, n))
            };
            if let Ok((e, n)) = repeat.parse2(m.tokens.clone()) {
                self.child(&e, Place::MacroArgument);
                self.child(&n, Place::MacroArgument);
                return true;
            }
        }
        let Ok(args) =
            Punctuated::<syn::Expr, syn::Token![,]>::parse_terminated.parse2(m.tokens.clone())
        else {
            return false;
        };
        let args: Vec<syn::Expr> = args.into_iter().collect();
        let format_at = format_position(name);
        // Before edition 2021 a lone message of these is printed as written.
        let lone = LONE_MESSAGE.contains(&name)
            && ["2015", "2018"].contains(&self.edition)
            && format_at.is_some_and(|at| args.len() == at + 1);
        let stringified = STRINGIFYING.contains(&name) && args.len() == 1;
        for (i, a) in args.iter().enumerate() {
            match a {
                syn::Expr::Lit(syn::ExprLit {
                    lit: syn::Lit::Str(s),
                    ..
                }) if Some(i) == format_at && !lone => self.format_spec(s),
                _ if stringified => {
                    let frozen = self.frozen;
                    self.frozen = Some(self.frozen.unwrap_or(Place::Stringified));
                    self.child(a, Place::Stringified);
                    self.frozen = frozen;
                }
                _ => self.child(a, Place::MacroArgument),
            }
        }
        true
    }

    /// The integers of a format string's specs (`{:>10}`, `{0:.3}`), at
    /// their bytes in the file: each a width, a precision or an argument
    /// index, which the format string itself must spell. The specs are read
    /// from the string's value, each character with the source bytes that
    /// spell it, so an escape (`\u{31}`, `\x7b`) is the one character it
    /// denotes, never the digits it is written with.
    fn format_spec(&mut self, s: &syn::LitStr) {
        let start = self.lines.byte(s.span().start());
        let end = self.lines.byte(s.span().end());
        let text = &self.lines.text[start..end.max(start)];
        let (Some(open), Some(close)) = (text.find('"'), text.rfind('"')) else {
            return;
        };
        if close <= open {
            return;
        }
        let raw = text.starts_with('r');
        let base = start + open + 1;
        let chars = string_chars(&text[open + 1..close], raw);
        let mut i = 0;
        while i < chars.len() {
            match chars[i].0 {
                '{' if chars.get(i + 1).map(|c| c.0) == Some('{') => i += 2,
                '{' => {
                    let close = (i..chars.len())
                        .find(|k| chars[*k].0 == '}')
                        .unwrap_or(chars.len());
                    let mut j = i + 1;
                    while j < close {
                        let c = chars[j].0;
                        if c.is_alphabetic() || c == '_' {
                            // A named argument: its digits are its name's.
                            while j < close && (chars[j].0.is_alphanumeric() || chars[j].0 == '_') {
                                j += 1;
                            }
                        } else if c.is_ascii_digit() {
                            let mut k = j;
                            while k < close && chars[k].0.is_ascii_digit() {
                                k += 1;
                            }
                            // A zero that leads a width is the zero-padding
                            // flag, not part of the width.
                            let from = if c == '0' && k > j + 1 { j + 1 } else { j };
                            let digits: String = chars[from..k].iter().map(|c| c.0).collect();
                            self.record_bytes(
                                (base + chars[from].1, base + chars[k - 1].2),
                                digits,
                                Place::FormatSpec,
                                Form::Literal,
                            );
                            j = k;
                        } else {
                            j += 1;
                        }
                    }
                    i = close + 1;
                }
                _ => i += 1,
            }
        }
    }
}

/// The position of a standard macro's format string, where it takes one.
fn format_position(name: &str) -> Option<usize> {
    if FORMAT_MACROS.contains(&name) {
        Some(0)
    } else if ["write", "writeln"].contains(&name) || STRINGIFYING.contains(&name) {
        Some(1)
    } else if PAIR_ASSERTIONS.contains(&name) {
        Some(2)
    } else {
        None
    }
}

/// The characters of a string literal's body (between its quotes), each
/// with the bytes of the body that spell it: an escape is one character
/// (the Reference, "String literals": `\n`, `\x7f`, `\u{..}`, a line
/// continuation that spells none); a raw string has none.
fn string_chars(body: &str, raw: bool) -> Vec<(char, usize, usize)> {
    let mut out = Vec::new();
    let mut it = body.char_indices().peekable();
    while let Some((at, c)) = it.next() {
        if c != '\\' || raw {
            out.push((c, at, at + c.len_utf8()));
            continue;
        }
        let Some((k, e)) = it.next() else {
            break;
        };
        match e {
            'u' => {
                let mut hex = String::new();
                let mut stop = k + 1;
                for (j, d) in it.by_ref() {
                    stop = j + d.len_utf8();
                    if d == '}' {
                        break;
                    }
                    if d.is_ascii_hexdigit() {
                        hex.push(d);
                    }
                }
                if let Some(ch) = u32::from_str_radix(&hex, 16).ok().and_then(char::from_u32) {
                    out.push((ch, at, stop));
                }
            }
            'x' => {
                let digits: Vec<(usize, char)> = it.by_ref().take(2).collect();
                let hex: String = digits.iter().map(|d| d.1).collect();
                let stop = digits.last().map_or(k + 1, |(j, d)| j + d.len_utf8());
                if let Some(ch) = u32::from_str_radix(&hex, 16).ok().and_then(char::from_u32) {
                    out.push((ch, at, stop));
                }
            }
            '\n' | '\r' => {
                while it.peek().is_some_and(|(_, w)| w.is_whitespace()) {
                    it.next();
                }
            }
            other => {
                let ch = match other {
                    'n' => '\n',
                    't' => '\t',
                    'r' => '\r',
                    '0' => '\0',
                    plain => plain,
                };
                out.push((ch, at, k + other.len_utf8()));
            }
        }
    }
    out
}

/// A literal's token text, exactly as written.
trait TokenText {
    fn to_token_stream_text(&self) -> String;
}

impl TokenText for syn::Lit {
    fn to_token_stream_text(&self) -> String {
        match self {
            syn::Lit::Int(i) => i.to_string(),
            syn::Lit::Float(f) => f.to_string(),
            other => quote::ToTokens::to_token_stream(other).to_string(),
        }
    }
}

fn span_bytes(lines: &Lines<'_>, t: &impl quote::ToTokens) -> (usize, usize) {
    let mut iter = t.to_token_stream().into_iter();
    let first = iter.next();
    let last = iter.last().or_else(|| first.clone());
    match (first, last) {
        (Some(a), Some(b)) => (lines.byte(a.span().start()), lines.byte(b.span().end())),
        _ => (0, 0),
    }
}

/// The numeric literals of a token tree, each with its span and its text as
/// written, but for a tuple index: a literal written right against a `.`
/// that is written right against an identifier, a literal or a closing
/// delimiter (`t.2`, `f().0`, `t.0.1`) is the field of a tuple (the
/// Reference, "Tuple indexing expressions"), not a number. A spaced `a . 3`
/// is read as a number, since a macro's grammar may make it one.
fn numeric_tokens(tokens: &TokenStream) -> Vec<(proc_macro2::Span, String)> {
    let trees: Vec<TokenTree> = tokens.clone().into_iter().collect();
    let touching = |a: proc_macro2::Span, b: proc_macro2::Span| a.end() == b.start();
    let mut out = Vec::new();
    for (i, tt) in trees.iter().enumerate() {
        match tt {
            TokenTree::Group(g) => out.extend(numeric_tokens(&g.stream())),
            TokenTree::Literal(l) => {
                let index = i >= 2
                    && matches!(&trees[i - 1], TokenTree::Punct(p)
                        if p.as_char() == '.' && touching(p.span(), l.span()))
                    && matches!(&trees[i - 2],
                        TokenTree::Ident(_) | TokenTree::Literal(_) | TokenTree::Group(_)
                            if touching(trees[i - 2].span(), trees[i - 1].span()));
                let numeric = syn::parse_str::<syn::Lit>(&l.to_string())
                    .is_ok_and(|lit| matches!(lit, syn::Lit::Int(_) | syn::Lit::Float(_)));
                if numeric && !index {
                    out.push((l.span(), l.to_string()));
                }
            }
            _ => {}
        }
    }
    out
}

/// Whether a code block's info string makes rustdoc compile it as a Rust
/// doc test: no language, or `rust`, or only rustdoc's own attributes
/// (`should_panic`, `no_run`, `compile_fail`, an edition, an error code,
/// ...); never under `ignore`, and not under another language's name.
fn rust_block(info: &str) -> bool {
    let tokens: Vec<&str> = info
        .split(|c: char| c == ',' || c.is_whitespace())
        .filter(|t| !t.is_empty())
        .collect();
    if tokens.contains(&"ignore") {
        return false;
    }
    let rustdoc = |t: &str| {
        [
            "rust",
            "should_panic",
            "no_run",
            "compile_fail",
            "test_harness",
            "standalone_crate",
            "allow_fail",
        ]
        .contains(&t)
            || t.starts_with("edition")
            || t.starts_with("ignore-")
            || t.starts_with('{')
            || (t.len() == 5 && t.starts_with('E') && t[1..].chars().all(|c| c.is_ascii_digit()))
    };
    tokens.contains(&"rust") || tokens.iter().all(|t| rustdoc(t))
}

/// A doc test's line as rustdoc compiles it: a hidden line's `#` (`# x`, a
/// lone `#`, or the first of `##`) is not compiled, so it is blanked, which
/// keeps every other character at its column.
fn doc_code_line(text: &str, at: usize) -> (String, usize) {
    let t = text.trim_start();
    let lead = text.len() - t.len();
    let hidden = t == "#" || t.starts_with("# ") || t.starts_with("##");
    let mut line = text.to_string();
    if hidden {
        line.replace_range(lead..=lead, " ");
    }
    (line, at)
}

/// The code blocks of a doc text that rustdoc compiles: each fenced block
/// whose info string is Rust's ([`rust_block`]), and each indented block
/// (four columns beyond the text's own indent, after a blank line or another
/// such line). `lines` are the doc's lines, each with the byte its text
/// starts at; each block is its lines so.
fn doc_code(lines: &[(String, usize)]) -> Vec<Vec<(String, usize)>> {
    let indent = lines
        .iter()
        .filter(|(l, _)| !l.trim().is_empty())
        .map(|(l, _)| l.len() - l.trim_start().len())
        .min()
        .unwrap_or(0);
    let mut blocks = Vec::new();
    let mut current: Vec<(String, usize)> = Vec::new();
    let mut fence: Option<(char, usize, bool)> = None;
    let mut indented = false;
    let mut blank_before = true;
    for (text, at) in lines {
        let t = text.trim_start();
        let lead = text.len() - t.len();
        if let Some((c, n, rust)) = fence {
            let run = t.chars().take_while(|x| *x == c).count();
            if run >= n && t.trim_start_matches(c).trim().is_empty() {
                if rust {
                    blocks.push(std::mem::take(&mut current));
                }
                fence = None;
                blank_before = false;
            } else if rust {
                current.push(doc_code_line(text, *at));
            }
            continue;
        }
        if t.is_empty() {
            if indented {
                current.push((String::new(), *at));
            }
            blank_before = true;
            continue;
        }
        let opener = t.chars().next().filter(|c| *c == '`' || *c == '~');
        if let Some(c) = opener {
            let n = t.chars().take_while(|x| *x == c).count();
            if n >= 3 && lead < indent + 4 {
                if indented {
                    blocks.push(std::mem::take(&mut current));
                    indented = false;
                }
                fence = Some((c, n, rust_block(&t[n..])));
                continue;
            }
        }
        if lead >= indent + 4 && (indented || blank_before) {
            indented = true;
            current.push(doc_code_line(text, *at));
            blank_before = false;
            continue;
        }
        if indented {
            blocks.push(std::mem::take(&mut current));
            indented = false;
        }
        blank_before = false;
    }
    // An unclosed fence runs to the end of the text, as rustdoc reads it.
    if indented || fence.is_some_and(|(_, _, rust)| rust) {
        blocks.push(current);
    }
    blocks
}

/// The literals of a doc text's doc tests, each with its bytes in the file
/// that holds the text, and the first byte of each block that does not lex.
fn doc_literals(lines: &[(String, usize)]) -> (Vec<(usize, usize, String)>, Vec<usize>) {
    let mut found = Vec::new();
    let mut unlexed = Vec::new();
    for block in doc_code(lines) {
        let code: Vec<&str> = block.iter().map(|(l, _)| l.as_str()).collect();
        let Ok(tokens) = code.join("\n").parse::<TokenStream>() else {
            unlexed.push(block.first().map_or(0, |(_, at)| *at));
            continue;
        };
        let byte = |lc: LineColumn| {
            block
                .get(lc.line.saturating_sub(1))
                .map(|(l, at)| at + l.char_indices().nth(lc.column).map_or(l.len(), |(i, _)| i))
        };
        for (span, text) in numeric_tokens(&tokens) {
            if let (Some(a), Some(b)) = (byte(span.start()), byte(span.end())) {
                found.push((a, b, text));
            }
        }
    }
    (found, unlexed)
}

/// The lines of a text, each with the byte it starts at, offset by `at`.
fn lines_at(text: &str, at: usize) -> Vec<(String, usize)> {
    let mut out = Vec::new();
    let mut off = at;
    for l in text.split('\n') {
        out.push((l.to_string(), off));
        off += l.len() + 1;
    }
    out
}

impl<'ast> Visit<'ast> for Walk<'_> {
    fn visit_attribute(&mut self, a: &'ast syn::Attribute) {
        let tokens = match &a.meta {
            syn::Meta::Path(_) => TokenStream::new(),
            syn::Meta::List(l) => l.tokens.clone(),
            syn::Meta::NameValue(nv) => quote::ToTokens::to_token_stream(&nv.value),
        };
        self.tokens(&tokens, Place::Attribute);
    }

    fn visit_item_fn(&mut self, i: &'ast syn::ItemFn) {
        self.scoped(&i.attrs, Some(i.sig.ident.to_string()), |w| {
            w.visit_signature(&i.sig);
            w.visit_block(&i.block);
        });
    }

    fn visit_impl_item_fn(&mut self, i: &'ast syn::ImplItemFn) {
        self.scoped(&i.attrs, Some(i.sig.ident.to_string()), |w| {
            w.visit_signature(&i.sig);
            w.visit_block(&i.block);
        });
    }

    fn visit_trait_item_fn(&mut self, i: &'ast syn::TraitItemFn) {
        self.scoped(&i.attrs, Some(i.sig.ident.to_string()), |w| {
            w.visit_signature(&i.sig);
            if let Some(b) = &i.default {
                w.visit_block(b);
            }
        });
    }

    fn visit_item_mod(&mut self, i: &'ast syn::ItemMod) {
        self.scoped(&i.attrs, Some(i.ident.to_string()), |w| {
            if let Some((_, items)) = &i.content {
                for item in items {
                    w.visit_item(item);
                }
            }
        });
    }

    fn visit_item_impl(&mut self, i: &'ast syn::ItemImpl) {
        let ty: String = quote::ToTokens::to_token_stream(&i.self_ty)
            .to_string()
            .split_whitespace()
            .collect();
        let name = match &i.trait_ {
            Some((t, _)) => {
                let t: String = quote::ToTokens::to_token_stream(t)
                    .to_string()
                    .split_whitespace()
                    .collect();
                format!("<{ty} as {t}>")
            }
            None => format!("<{ty}>"),
        };
        self.scoped(&i.attrs, Some(name), |w| {
            w.visit_generics(&i.generics);
            w.visit_type(&i.self_ty);
            for item in &i.items {
                w.visit_impl_item(item);
            }
        });
    }

    fn visit_item_trait(&mut self, i: &'ast syn::ItemTrait) {
        self.scoped(&i.attrs, Some(i.ident.to_string()), |w| {
            w.visit_generics(&i.generics);
            for item in &i.items {
                w.visit_trait_item(item);
            }
        });
    }

    fn visit_item_struct(&mut self, i: &'ast syn::ItemStruct) {
        self.scoped(&i.attrs, Some(i.ident.to_string()), |w| {
            w.visit_generics(&i.generics);
            w.visit_fields(&i.fields);
        });
    }

    fn visit_item_enum(&mut self, i: &'ast syn::ItemEnum) {
        self.scoped(&i.attrs, Some(i.ident.to_string()), |w| {
            w.visit_generics(&i.generics);
            for v in &i.variants {
                w.visit_variant(v);
            }
        });
    }

    fn visit_item_type(&mut self, i: &'ast syn::ItemType) {
        self.scoped(&i.attrs, Some(i.ident.to_string()), |w| {
            w.visit_generics(&i.generics);
            w.visit_type(&i.ty);
        });
    }

    fn visit_item_const(&mut self, i: &'ast syn::ItemConst) {
        self.scoped(&i.attrs, Some(i.ident.to_string()), |w| {
            w.visit_type(&i.ty);
            w.child(&i.expr, Place::Initializer);
        });
    }

    fn visit_item_static(&mut self, i: &'ast syn::ItemStatic) {
        self.scoped(&i.attrs, Some(i.ident.to_string()), |w| {
            w.visit_type(&i.ty);
            w.child(&i.expr, Place::Initializer);
        });
    }

    fn visit_impl_item_const(&mut self, i: &'ast syn::ImplItemConst) {
        self.scoped(&i.attrs, Some(i.ident.to_string()), |w| {
            w.visit_type(&i.ty);
            w.child(&i.expr, Place::Initializer);
        });
    }

    fn visit_trait_item_const(&mut self, i: &'ast syn::TraitItemConst) {
        self.scoped(&i.attrs, Some(i.ident.to_string()), |w| {
            w.visit_type(&i.ty);
            if let Some((_, e)) = &i.default {
                w.child(e, Place::Initializer);
            }
        });
    }

    fn visit_item_macro(&mut self, i: &'ast syn::ItemMacro) {
        let name = i
            .ident
            .as_ref()
            .map_or_else(|| "macro".to_string(), ToString::to_string);
        let whole = span_bytes(self.lines, &i.mac);
        self.scoped(&i.attrs, Some(name), |w| w.mac(&i.mac, whole));
    }

    fn visit_item_union(&mut self, i: &'ast syn::ItemUnion) {
        self.scoped(&i.attrs, Some(i.ident.to_string()), |w| {
            w.visit_generics(&i.generics);
            w.visit_fields_named(&i.fields);
        });
    }

    fn visit_item_trait_alias(&mut self, i: &'ast syn::ItemTraitAlias) {
        self.scoped(&i.attrs, Some(i.ident.to_string()), |w| {
            w.visit_generics(&i.generics);
            for b in &i.bounds {
                w.visit_type_param_bound(b);
            }
        });
    }

    fn visit_item_foreign_mod(&mut self, i: &'ast syn::ItemForeignMod) {
        self.scoped(&i.attrs, None, |w| {
            for item in &i.items {
                w.visit_foreign_item(item);
            }
        });
    }

    fn visit_item_use(&mut self, i: &'ast syn::ItemUse) {
        self.scoped(&i.attrs, None, |_| {});
    }

    fn visit_item_extern_crate(&mut self, i: &'ast syn::ItemExternCrate) {
        self.scoped(&i.attrs, None, |_| {});
    }

    fn visit_impl_item_type(&mut self, i: &'ast syn::ImplItemType) {
        self.scoped(&i.attrs, Some(i.ident.to_string()), |w| {
            w.visit_generics(&i.generics);
            w.visit_type(&i.ty);
        });
    }

    fn visit_trait_item_type(&mut self, i: &'ast syn::TraitItemType) {
        self.scoped(&i.attrs, Some(i.ident.to_string()), |w| {
            w.visit_generics(&i.generics);
            for b in &i.bounds {
                w.visit_type_param_bound(b);
            }
            if let Some((_, t)) = &i.default {
                w.visit_type(t);
            }
        });
    }

    fn visit_foreign_item_fn(&mut self, i: &'ast syn::ForeignItemFn) {
        self.scoped(&i.attrs, Some(i.sig.ident.to_string()), |w| {
            w.visit_signature(&i.sig);
        });
    }

    fn visit_foreign_item_static(&mut self, i: &'ast syn::ForeignItemStatic) {
        self.scoped(&i.attrs, Some(i.ident.to_string()), |w| w.visit_type(&i.ty));
    }

    fn visit_foreign_item_type(&mut self, i: &'ast syn::ForeignItemType) {
        self.scoped(&i.attrs, Some(i.ident.to_string()), |w| {
            w.visit_generics(&i.generics);
        });
    }

    fn visit_impl_item_macro(&mut self, i: &'ast syn::ImplItemMacro) {
        let whole = span_bytes(self.lines, &i.mac);
        self.scoped(&i.attrs, None, |w| w.mac(&i.mac, whole));
    }

    fn visit_trait_item_macro(&mut self, i: &'ast syn::TraitItemMacro) {
        let whole = span_bytes(self.lines, &i.mac);
        self.scoped(&i.attrs, None, |w| w.mac(&i.mac, whole));
    }

    fn visit_foreign_item_macro(&mut self, i: &'ast syn::ForeignItemMacro) {
        let whole = span_bytes(self.lines, &i.mac);
        self.scoped(&i.attrs, None, |w| w.mac(&i.mac, whole));
    }

    /// A macro call in any position no visit above names: its tokens.
    fn visit_macro(&mut self, m: &'ast syn::Macro) {
        let whole = span_bytes(self.lines, m);
        self.mac(m, whole);
    }

    fn visit_field(&mut self, f: &'ast syn::Field) {
        self.docs(&f.attrs);
        visit::visit_field(self, f);
    }

    // Tokens syn keeps unparsed (a form its grammar lacks) are a macro's
    // tokens as far as a rewrite knows: counted, never placed.

    fn visit_item(&mut self, i: &'ast syn::Item) {
        match i {
            syn::Item::Verbatim(t) => self.tokens(t, Place::MacroTokens),
            other => visit::visit_item(self, other),
        }
    }

    fn visit_expr(&mut self, e: &'ast syn::Expr) {
        match e {
            syn::Expr::Verbatim(t) => self.tokens(t, Place::MacroTokens),
            other => visit::visit_expr(self, other),
        }
    }

    fn visit_type(&mut self, t: &'ast syn::Type) {
        match t {
            syn::Type::Verbatim(v) => self.tokens(v, Place::MacroTokens),
            other => visit::visit_type(self, other),
        }
    }

    fn visit_impl_item(&mut self, i: &'ast syn::ImplItem) {
        match i {
            syn::ImplItem::Verbatim(t) => self.tokens(t, Place::MacroTokens),
            other => visit::visit_impl_item(self, other),
        }
    }

    fn visit_trait_item(&mut self, i: &'ast syn::TraitItem) {
        match i {
            syn::TraitItem::Verbatim(t) => self.tokens(t, Place::MacroTokens),
            other => visit::visit_trait_item(self, other),
        }
    }

    fn visit_foreign_item(&mut self, i: &'ast syn::ForeignItem) {
        match i {
            syn::ForeignItem::Verbatim(t) => self.tokens(t, Place::MacroTokens),
            other => visit::visit_foreign_item(self, other),
        }
    }

    fn visit_stmt_macro(&mut self, s: &'ast syn::StmtMacro) {
        for a in &s.attrs {
            self.visit_attribute(a);
        }
        let whole = span_bytes(self.lines, &s.mac);
        self.mac(&s.mac, whole);
    }

    fn visit_expr_macro(&mut self, e: &'ast syn::ExprMacro) {
        for a in &e.attrs {
            self.visit_attribute(a);
        }
        let whole = span_bytes(self.lines, &e.mac);
        self.mac(&e.mac, whole);
    }

    fn visit_type_macro(&mut self, t: &'ast syn::TypeMacro) {
        let whole = span_bytes(self.lines, &t.mac);
        self.mac(&t.mac, whole);
    }

    fn visit_expr_lit(&mut self, e: &'ast syn::ExprLit) {
        for a in &e.attrs {
            self.visit_attribute(a);
        }
        self.lit(&e.lit, Place::Expression);
    }

    fn visit_expr_binary(&mut self, e: &'ast syn::ExprBinary) {
        for a in &e.attrs {
            self.visit_attribute(a);
        }
        let place = match e.op {
            syn::BinOp::Eq(_)
            | syn::BinOp::Ne(_)
            | syn::BinOp::Lt(_)
            | syn::BinOp::Le(_)
            | syn::BinOp::Gt(_)
            | syn::BinOp::Ge(_) => Place::Comparison,
            _ => Place::Operand,
        };
        self.child(&e.left, place);
        self.child(&e.right, place);
    }

    fn visit_expr_index(&mut self, e: &'ast syn::ExprIndex) {
        for a in &e.attrs {
            self.visit_attribute(a);
        }
        self.visit_expr(&e.expr);
        self.child(&e.index, Place::Index);
    }

    fn visit_expr_call(&mut self, e: &'ast syn::ExprCall) {
        for a in &e.attrs {
            self.visit_attribute(a);
        }
        self.visit_expr(&e.func);
        for a in &e.args {
            self.child(a, Place::Argument);
        }
    }

    fn visit_expr_method_call(&mut self, e: &'ast syn::ExprMethodCall) {
        for a in &e.attrs {
            self.visit_attribute(a);
        }
        self.visit_expr(&e.receiver);
        if let Some(t) = &e.turbofish {
            self.visit_angle_bracketed_generic_arguments(t);
        }
        for a in &e.args {
            self.child(a, Place::Argument);
        }
    }

    fn visit_expr_repeat(&mut self, e: &'ast syn::ExprRepeat) {
        for a in &e.attrs {
            self.visit_attribute(a);
        }
        self.visit_expr(&e.expr);
        self.child(&e.len, Place::ArrayLength);
    }

    fn visit_type_array(&mut self, t: &'ast syn::TypeArray) {
        self.visit_type(&t.elem);
        self.child(&t.len, Place::ArrayLength);
    }

    fn visit_generic_argument(&mut self, g: &'ast syn::GenericArgument) {
        match g {
            syn::GenericArgument::Const(e) => self.child(e, Place::ConstGeneric),
            other => visit::visit_generic_argument(self, other),
        }
    }

    fn visit_const_param(&mut self, p: &'ast syn::ConstParam) {
        for a in &p.attrs {
            self.visit_attribute(a);
        }
        self.visit_type(&p.ty);
        if let Some((_, d)) = &p.default {
            self.child(d, Place::ConstGeneric);
        }
    }

    fn visit_variant(&mut self, v: &'ast syn::Variant) {
        self.scoped(&v.attrs, Some(v.ident.to_string()), |w| {
            w.visit_fields(&v.fields);
            if let Some((_, d)) = &v.discriminant {
                w.child(d, Place::Discriminant);
            }
        });
    }

    fn visit_pat(&mut self, p: &'ast syn::Pat) {
        match p {
            syn::Pat::Lit(l) => {
                if !self.lit(&l.lit, Place::Pattern) {
                    visit::visit_pat(self, p);
                }
            }
            syn::Pat::Range(r) => {
                for bound in [&r.start, &r.end].into_iter().flatten() {
                    match &**bound {
                        syn::Expr::Lit(l) => {
                            self.lit(&l.lit, Place::RangeBound);
                        }
                        syn::Expr::Path(path) => self.generated_constant(path),
                        other => self.visit_expr(other),
                    }
                }
            }
            syn::Pat::Macro(m) => {
                let whole = span_bytes(self.lines, &m.mac);
                self.mac(&m.mac, whole);
            }
            syn::Pat::Verbatim(t) => self.tokens(t, Place::MacroTokens),
            other => visit::visit_pat(self, other),
        }
    }
}

impl Walk<'_> {
    /// A range-pattern bound written as the generated constant of a figure.
    fn generated_constant(&mut self, path: &syn::ExprPath) {
        let segs: Vec<String> = path
            .path
            .segments
            .iter()
            .map(|s| s.ident.to_string())
            .collect();
        if let [k, name] = segs.as_slice() {
            let lower = name.to_ascii_lowercase();
            if self.krates.contains(k) && *name == constant_name(&lower) {
                let literal = self.figures.get(&lower).cloned().unwrap_or_default();
                let whole = span_bytes(self.lines, path);
                self.record_bytes(whole, literal, Place::RangeBound, Form::Constant(lower));
            }
        }
    }
}

/// The typed constant's name of a figure.
fn constant_name(figure: &str) -> String {
    figure.to_ascii_uppercase()
}

/// The names a file binds that may stand for a macro: `macro_rules! name`,
/// a `use` of another crate or module's item under a name (`use path::name;`,
/// `use path::x as name;`), a procedural macro the workspace defines
/// (`#[proc_macro]`, `#[proc_macro_attribute]`, `#[proc_macro_derive(Name)]`
/// with its helper attributes), and, for a `#[macro_use] extern crate` of
/// another crate, every standard name. A standard macro, derive or prelude
/// attribute of such a name may be the workspace's, so its tokens are not
/// read by the standard grammar. A `use` of the standard library's own item
/// binds the standard item, so it shadows nothing.
///
/// A glob binds no name here. The language resolves a macro, derive or
/// attribute name that a glob import brings into a scope and that a scope
/// outside it (the standard library's preludes among them) also binds as an
/// ambiguity, which is an error wherever the name is used (rustc's E0659,
/// "a conflict between a name from a glob import and an outer scope during
/// import or macro resolution"; seen at the pinned toolchain in editions
/// 2015, 2018 and 2021, for a bang macro, a derive and a prelude attribute).
/// So in a program that compiles, a glob never changes which macro a
/// standard name the preludes bind denotes, in its own module or any other.
/// That holds only where a prelude binds the name: the function returns
/// whether the file has a glob of another crate, and [`load`] treats such a
/// glob as binding every standard name when any file of the workspace drops
/// a prelude ([`without_prelude`]).
fn bound_macro_names(
    file: &syn::File,
    local: &BTreeSet<String>,
    out: &mut BTreeSet<String>,
) -> bool {
    struct Names<'o> {
        local: &'o BTreeSet<String>,
        out: &'o mut BTreeSet<String>,
        foreign_glob: bool,
    }
    impl Names<'_> {
        fn tree(&mut self, t: &syn::UseTree, root: Option<&str>) {
            let standard = root.is_some_and(|r| ["std", "core", "alloc"].contains(&r));
            match t {
                syn::UseTree::Path(p) => {
                    let first = root.map_or_else(|| p.ident.to_string(), str::to_string);
                    self.tree(&p.tree, Some(&first));
                }
                syn::UseTree::Name(n) if !standard => {
                    self.out.insert(n.ident.to_string());
                }
                syn::UseTree::Rename(r) if !standard => {
                    self.out.insert(r.rename.to_string());
                }
                syn::UseTree::Name(_) | syn::UseTree::Rename(_) => {}
                syn::UseTree::Group(g) => {
                    for t in &g.items {
                        self.tree(t, root);
                    }
                }
                // A glob from the workspace's own modules or crates brings
                // in only names the workspace defines, which are already
                // named; a glob from the standard library brings in its own
                // items; a glob from any other crate may bring in any name,
                // which a prelude's binding of the same name makes an error.
                syn::UseTree::Glob(_) => {
                    let inside = root.is_some_and(|r| {
                        ["crate", "self", "super", "std", "core", "alloc"].contains(&r)
                            || self.local.contains(r)
                    });
                    self.foreign_glob |= !inside;
                }
            }
        }
    }
    impl<'ast> Visit<'ast> for Names<'_> {
        fn visit_item_macro(&mut self, i: &'ast syn::ItemMacro) {
            if let Some(id) = &i.ident {
                self.out.insert(id.to_string());
            }
        }
        fn visit_item_use(&mut self, u: &'ast syn::ItemUse) {
            self.tree(&u.tree, None);
        }
        fn visit_item_extern_crate(&mut self, e: &'ast syn::ItemExternCrate) {
            let name = e.ident.to_string();
            let standard = ["std", "core", "alloc"].contains(&name.as_str());
            if e.attrs.iter().any(|a| a.path().is_ident("macro_use")) && !standard {
                every_standard_name(self.out);
            }
        }
        fn visit_item_fn(&mut self, f: &'ast syn::ItemFn) {
            for a in &f.attrs {
                if a.path().is_ident("proc_macro") || a.path().is_ident("proc_macro_attribute") {
                    self.out.insert(f.sig.ident.to_string());
                }
                if a.path().is_ident("proc_macro_derive") {
                    if let syn::Meta::List(l) = &a.meta {
                        // The derive's name and its helper attributes' names.
                        for tt in l.tokens.clone() {
                            match tt {
                                TokenTree::Ident(i) if i != "attributes" => {
                                    self.out.insert(i.to_string());
                                }
                                TokenTree::Group(g) => {
                                    for inner in g.stream() {
                                        if let TokenTree::Ident(i) = inner {
                                            self.out.insert(i.to_string());
                                        }
                                    }
                                }
                                _ => {}
                            }
                        }
                    }
                }
            }
            visit::visit_item_fn(self, f);
        }
    }
    let mut names = Names {
        local,
        out,
        foreign_glob: false,
    };
    names.visit_file(file);
    names.foreign_glob
}

/// Whether a file drops a prelude anywhere: `no_std` (the standard
/// library's macros are then in no prelude) or `no_implicit_prelude` (no
/// prelude at all), written as an attribute or inside a `cfg_attr`. Where a
/// prelude does not bind a standard name, a glob that brings the name in is
/// no ambiguity, so it may bind the name to another crate's macro.
fn without_prelude(file: &syn::File) -> bool {
    struct Reader(bool);
    fn names(tokens: &TokenStream) -> bool {
        tokens.clone().into_iter().any(|tt| match tt {
            TokenTree::Ident(i) => i == "no_std" || i == "no_implicit_prelude",
            TokenTree::Group(g) => names(&g.stream()),
            _ => false,
        })
    }
    impl<'ast> Visit<'ast> for Reader {
        fn visit_attribute(&mut self, a: &'ast syn::Attribute) {
            self.0 |= names(&quote::ToTokens::to_token_stream(&a.meta));
        }
    }
    let mut reader = Reader(false);
    reader.visit_file(file);
    reader.0
}

/// Every name a standard macro, derive or prelude attribute macro has.
fn every_standard_name(out: &mut BTreeSet<String>) {
    for name in EXPRESSION_MACROS
        .iter()
        .chain(FORMAT_MACROS.iter())
        .chain(STANDARD_DERIVES.iter())
        .chain(SHADOWABLE_ATTRIBUTES.iter())
    {
        out.insert((*name).to_string());
    }
}

/// What reads the location of its own call, read from the source of the
/// workspace and of every package its build resolves (the dependencies'
/// own sources at the locked versions, outside the workspace's path
/// dependencies included): the functions marked `#[track_caller]`, written
/// so or inside a `cfg_attr` (the Reference, "track_caller": the attribute
/// makes `Location::caller()` in the body, and the location passed on to a
/// tracked call in it, the caller's); the functions a `macro_rules!` macro
/// writes with that attribute (the names its body writes after `fn`, and the
/// identifiers of its calls); the names a `use ... as` gives any of them;
/// and the `macro_rules!` macros whose body names `line`, `column`, `caller`,
/// or such a function or macro (a fixpoint).
///
/// A tracked function reads a value of its caller's place only when its
/// body names `caller`, or a function or macro that reads one, or calls a
/// macro the figures do not read; one that only passes the location on to a
/// panic (`unwrap`, `expect`, indexing, `panic!`) reports it in a panic
/// message, which is the location the MIR proof states it leaves to
/// `cargo test` (figures-5-6). A bodiless trait method marked so reads
/// (its impls inherit the attribute).
///
/// What a token reading cannot see is `unknown`, with the first place that
/// shows it: a tracked function under an attribute macro (the macro may
/// emit other tracked items), a macro that is not a `macro_rules!` the
/// figures read called with `track_caller` in its tokens (a procedural
/// macro, or a dependency's macro under a name no read file defines), a
/// macro call with `track_caller` in its tokens inside a procedural macro
/// crate (code that crate emits, as `quote!` builds it), a
/// `macro_rules!` that builds a function's name or reaches such a macro, a
/// file syn cannot parse, or a dependency graph that cannot be resolved
/// offline. Then a call of any name may reach a tracked function, and
/// [`location_lines`] takes every line that calls one to read its column.
#[derive(Default)]
struct Locating {
    /// Each function marked `#[track_caller]`: its name and, when it has a
    /// body, the identifiers and the macro calls of the body.
    tracked: Vec<(String, Option<TrackedBody>)>,
    /// Each `macro_rules!` macro of the workspace: its name, the identifiers
    /// of its body and the paths of the macros its body calls.
    macros: Vec<(String, BTreeSet<String>, Vec<Vec<String>>)>,
    /// Each `macro_rules!` macro read, the dependencies' included: its
    /// name, the identifiers of its body, the macros its body calls, and the
    /// names its body writes after `fn`.
    every: Vec<RulesMacro>,
    /// Each macro call outside a `macro_rules!` body: the last segment of
    /// its path and the identifiers of its tokens.
    invocations: Vec<(String, BTreeSet<String>)>,
    /// Each `use` that renames: the name it imports and the name it binds.
    renames: Vec<(String, String)>,
    /// Each tracked function with the attributes on it and on the items
    /// around it (any of them may be an attribute macro, which may emit
    /// other tracked items), and its place.
    attributed: Vec<(String, Vec<syn::Meta>)>,
    /// The first place that shows a tracked function the source does not
    /// name.
    unknown: Option<String>,
    /// Whether the file read is a procedural macro crate's, whose macro
    /// calls build the code it emits.
    generator: bool,
}

/// The body of a tracked function: its identifiers and the paths of the
/// macros it calls.
type TrackedBody = (BTreeSet<String>, Vec<Vec<String>>);

/// One `macro_rules!` macro as [`Locating`] reads it.
struct RulesMacro {
    name: String,
    body: BTreeSet<String>,
    calls: Vec<Vec<String>>,
    /// The identifiers its body writes after `fn`; `None` when a `fn` is
    /// followed by something that is neither an identifier nor `$` (a
    /// name some other macro builds).
    functions: Option<BTreeSet<String>>,
}

/// What reads the place it is called from, as [`Locating`] closed it:
/// `reading` the functions and macros whose call reads its own location,
/// `quiet` the workspace's `macro_rules!` macros that do not, `bound` the
/// names the workspace binds to a macro (`shadowed` of [`load`]), which no
/// standard macro's reading speaks for, `generated` the names the
/// workspace's packages bind the generated package under, whose macros
/// expand to a literal token and nothing else, and `calls` why a call of any
/// name may read its column ([`Locating`]'s `unknown`).
#[derive(Clone, Default)]
struct Located {
    reading: BTreeSet<String>,
    quiet: BTreeSet<String>,
    bound: BTreeSet<String>,
    generated: BTreeSet<String>,
    calls: Option<String>,
}

