    fn figures_repair_a_layout_that_moves_a_line_reading_its_line_is_refused() {
        let table = "pub fn table() -> [u32; 4] {\n    [1001, 1002, 1003, 1004]\n}\n";
        let here = "\npub fn here() -> u32 {\n    line!()\n}\n";
        let rows = figures_repair_figure_rows(&[
            (
                "the_first_entry_of_the_table",
                "1001",
                "\"p/p::table:1001:0\"",
            ),
            (
                "the_second_entry_of_the_table",
                "1002",
                "\"p/p::table:1002:0\"",
            ),
            (
                "the_third_entry_of_the_table",
                "1003",
                "\"p/p::table:1003:0\"",
            ),
            (
                "the_fourth_entry_of_the_table",
                "1004",
                "\"p/p::table:1004:0\"",
            ),
        ]);
        let run = |tag: &str, lib: &str| {
            let dir = figures_repair_workspace(
                tag,
                &[
                    ("Cargo.toml", FIGURES_REPAIR_ROOT),
                    (
                        "p/Cargo.toml",
                        &figures_repair_manifest("figs = { path = \"../figs\" }\n"),
                    ),
                    ("p/src/lib.rs", lib),
                    ("figs/Cargo.toml", FIGURES_REPAIR_FIGS),
                    ("figs/src/lib.rs", "#![no_std]\n"),
                    ("rules.toml", FIGURES_REPAIR_RULES),
                    ("figures.toml", &rows),
                ],
            );
            let done = rewrite(&dir, &dir.join("rules.toml"), &dir.join("figures.toml"))
                .expect("rewritten");
            let after = std::fs::read_to_string(dir.join("p/src/lib.rs")).expect("read");
            let _ = std::fs::remove_dir_all(&dir);
            (done, after)
        };
        // The replaced line is too long for one line: the formatter breaks
        // it, and every line below moves.
        let (alone, after) = run("layout-alone", table);
        assert_eq!(alone.replaced, 4, "{:?}", alone.refused);
        assert!(after.lines().count() > table.lines().count(), "{after}");
        let lib = format!("{table}{here}");
        // Beside a line that reads its own line, each site is kept only while
        // the layout moves no line: the first fits, the rest are refused.
        let (located, after) = run("layout-line", &lib);
        assert_eq!(located.replaced, 1, "{:?}", located.refused);
        assert!(located
            .refused
            .iter()
            .all(|r| r.why
                == "the formatter's layout moves a line that reads its own line or column"));
        assert_eq!(located.refused.len(), 3);
        let at = |t: &str| t.lines().position(|l| l.contains("line!()"));
        assert_eq!(at(&after), at(&lib));
        assert!(
            after.contains("::figs::the_first_entry_of_the_table!()"),
            "{after}"
        );
    }

