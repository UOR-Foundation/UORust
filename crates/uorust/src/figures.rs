    /// The formatter's choices between a block that holds only a tail
    /// expression and the expression, in a match arm or a closure body, and
    /// a trailing comma after a call's or a signature's last element, are one
    /// program; a block with anything more, a closure with a stated return
    /// type, or a trailing comma that makes a tuple is not the same.
    #[test]
    fn figures_layout_a_tail_block_or_a_trailing_comma_is_one_program_ue_21() {
        let none = BTreeSet::new();
        let same = |a: &str, b: &str| same_program(a, b, &none);
        let arm = "fn p(n: usize, a: u64) -> u64 {\n    match n {\n        12 => g(a, a),\n        _ => 0,\n    }\n}\n";
        let block = "fn p(n: usize, a: u64) -> u64 {\n    match n {\n        12 => {\n            g(a, a)\n        }\n        _ => 0,\n    }\n}\n";
        assert!(same(arm, block));
        assert!(same(block, arm));
        let shadowing = "fn p(n: usize, a: u64) -> u64 {\n    match n {\n        12 => {\n            let a = 1;\n            g(a, a)\n        }\n        _ => 0,\n    }\n}\n";
        assert!(!same(arm, shadowing));
        let statement = "fn p(n: usize, a: u64) -> u64 {\n    match n {\n        12 => {\n            g(a, a);\n        }\n        _ => 0,\n    }\n}\n";
        assert!(!same(arm, statement));
        let labelled = "fn p(n: usize, a: u64) -> u64 {\n    match n {\n        12 => 'b: {\n            g(a, a)\n        }\n        _ => 0,\n    }\n}\n";
        assert!(!same(arm, labelled));
        // A standard macro as the arm's tail; a macro of unknown grammar is
        // not read as an expression.
        assert!(same(
            "fn p(n: u8) -> String { match n { 1 => format!(\"{}\", n), _ => String::new() } }",
            "fn p(n: u8) -> String { match n { 1 => { format!(\"{}\", n) } _ => String::new() } }"
        ));
        assert!(!same(
            "fn p(n: u8) -> String { match n { 1 => m!(n), _ => String::new() } }",
            "fn p(n: u8) -> String { match n { 1 => { m!(n) } _ => String::new() } }"
        ));
        // A closure's body.
        assert!(same(
            "fn p(v: &[u64]) -> u64 { v.iter().map(|x| x * 12).sum() }",
            "fn p(v: &[u64]) -> u64 {\n    v.iter()\n        .map(|x| {\n            x * 12\n        })\n        .sum()\n}\n"
        ));
        // A trailing comma after a single argument or parameter.
        assert!(same(
            "fn p(e: &[u64; 12]) -> u64 { q(e[0]) }",
            "fn p(\n    e: &[u64; 12],\n) -> u64 {\n    q(\n        e[0],\n    )\n}\n"
        ));
        assert!(same(
            "fn p(e: u64) -> u64 { e.max(3) }",
            "fn p(e: u64) -> u64 { e.max(3,) }"
        ));
        // The value inside still decides.
        assert!(!same(arm, &block.replace("g(a, a)", "g(a, 1)")));
    }

