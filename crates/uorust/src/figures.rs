        // One that makes a tuple of a parenthesized expression, or that a
        // macro of unknown grammar reads, is not nothing.
        assert!(!same("fn f() -> u8 { (2) }", "fn f() -> u8 { (2,) }"));
        assert!(!same("fn f() { m!(2, 3) }", "fn f() { m!(2, 3,) }"));
