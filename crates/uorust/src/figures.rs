const LEXLEAN_WIDTH: usize = 100;

/// The kinds of home a figure can have.
pub const HOMES: [&str; 4] = ["authority", "parameter", "derived", "definition"];

/// Where a literal stands, as far as a rewrite needs to know.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub enum Place {
    /// An expression the parents below do not name.
    Expression,
    /// An operand of an arithmetic or bit operator.
    Operand,
    /// An operand of a comparison.
    Comparison,
    /// An index.
    Index,
    /// An argument of a function or method call.
    Argument,
    /// The value of a `const` or `static` item.
    Initializer,
    /// An array length, in a type or a repeat expression.
    ArrayLength,
    /// An enum variant's discriminant.
    Discriminant,
    /// An expression argument of a standard macro.
    MacroArgument,
    /// A const generic argument or a const parameter's default: Rust needs
    /// braces around anything but a literal or a path there.
    ConstGeneric,
    /// A literal pattern.
    Pattern,
    /// A negative literal pattern: a macro call cannot be negated there.
    NegativePattern,
    /// A bound of a range pattern: a macro cannot stand there, a path can.
    RangeBound,
    /// The condition `assert!` prints as written.
    Stringified,
    /// The body of a `macro_rules!` definition.
    MacroRules,
    /// The token tree of a macro whose grammar is not known here.
    MacroTokens,
    /// An attribute's tokens.
    Attribute,
    /// A width, precision or argument index inside a format string.
    FormatSpec,
    /// The code of a doc test: rustdoc compiles it from the comment's text.
    DocTest,
}

impl Place {
    /// The name rows carry.
    pub fn name(self) -> &'static str {
        match self {
            Self::Expression => "expression",
            Self::Operand => "operand",
            Self::Comparison => "comparison",
            Self::Index => "index",
            Self::Argument => "argument",
            Self::Initializer => "initializer",
            Self::ArrayLength => "array-length",
            Self::Discriminant => "discriminant",
            Self::MacroArgument => "macro-argument",
            Self::ConstGeneric => "const-generic",
            Self::Pattern => "pattern",
            Self::NegativePattern => "negative-pattern",
            Self::RangeBound => "range-bound",
            Self::Stringified => "stringified",
            Self::MacroRules => "macro-rules",
            Self::MacroTokens => "macro-tokens",
            Self::Attribute => "attribute",
            Self::FormatSpec => "format-spec",
            Self::DocTest => "doc-test",
        }
    }

    /// Why no rewrite can place a figure here, when none can: the typed
    /// row a rewrite records.
    pub fn refusal(self) -> Option<&'static str> {
        match self {
            Self::NegativePattern => Some("a negated literal pattern admits no macro call"),
            Self::Stringified => Some("the standard library prints this condition as written"),
            Self::MacroRules => Some("a literal inside a macro_rules! definition"),
            Self::MacroTokens => {
                Some("a literal in the tokens of a macro whose grammar is unknown")
            }
            Self::Attribute => Some("a literal in an attribute"),
            Self::FormatSpec => Some("a format string must be a literal"),
            Self::DocTest => Some("a doc test is compiled from a comment's text"),
            _ => None,
        }
    }
}

/// How a site is written now.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Form {
    /// As a literal token.
    Literal,
    /// As the generated macro of the named figure.
    Macro(String),
    /// As the generated typed constant of the named figure.
    Constant(String),
}

/// One numeric-literal site of the workspace.
