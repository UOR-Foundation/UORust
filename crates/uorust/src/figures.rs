/// The methods a dereference calls where the source writes no token at
/// all (auto-deref of a receiver or a field access, a deref coercion):
/// a tracked one that reads its caller makes every call unknown.
const UNSPELLED: [&str; 2] = ["deref", "deref_mut"];

/// Each macro call of a token tree (a path, `!`, then a delimited group or,
/// for `macro_rules!`, a name): its path's segments (a `$crate` segment as
/// `crate`, any other segment after `$` as the metavariable it is, `$name`)
/// and the line its last segment stands on.
fn macro_calls(tokens: &TokenStream, out: &mut Vec<(Vec<String>, usize)>) {
    let tokens: Vec<TokenTree> = tokens.clone().into_iter().collect();
    let colon =
        |t: Option<&TokenTree>| matches!(t, Some(TokenTree::Punct(p)) if p.as_char() == ':');
    for (i, t) in tokens.iter().enumerate() {
        match t {
            TokenTree::Group(g) => macro_calls(&g.stream(), out),
            TokenTree::Ident(id) => {
                let bang = matches!(
                    tokens.get(i + 1),
                    Some(TokenTree::Punct(p))
                        if p.as_char() == '!' && p.spacing() == proc_macro2::Spacing::Alone
                );
                let body = matches!(
                    tokens.get(i + 2),
                    Some(TokenTree::Group(_) | TokenTree::Ident(_))
                );
                let text = id.to_string();
                let name = text.strip_prefix("r#").unwrap_or(&text).to_string();
                if !bang || !body || KEYWORDS.contains(&name.as_str()) && !text.starts_with("r#") {
                    continue;
                }
                let mut path = vec![name];
                let mut j = i;
                while j >= 3 && colon(tokens.get(j - 1)) && colon(tokens.get(j - 2)) {
                    let TokenTree::Ident(seg) = &tokens[j - 3] else {
                        break;
                    };
                    let word = seg.to_string();
                    if KEYWORDS.contains(&word.as_str())
                        && !["crate", "self", "super"].contains(&word.as_str())
                    {
                        break;
                    }
                    path.insert(0, seg.to_string());
                    j -= 3;
                }
                // A metavariable names whatever macro the caller passes.
                let dollar =
                    j >= 1 && matches!(&tokens[j - 1], TokenTree::Punct(p) if p.as_char() == '$');
                if dollar && path[0] != "crate" {
                    path[0] = format!("${}", path[0]);
                }
                out.push((path, id.span().start().line));
            }
            TokenTree::Punct(_) | TokenTree::Literal(_) => {}
        }
    }
}

/// Whether a call of the macro at `path` may hold a value of the place it
/// is called from. A workspace macro reads one when [`Locating`] says so; a
/// standard macro of the figures' lists or of [`QUIET_STANDARD_MACROS`] does
/// not, unless the workspace binds its name; `line!` and `column!` do; any
/// other macro, a registry crate's or a metavariable's among them, is not
/// read here, so it is taken to read its line and its column (a structured
/// logging macro stores `line!()` in a static of each call).
fn locating_call(path: &[String], located: &Located) -> bool {
    let Some(name) = path.last().map(String::as_str) else {
        return false;
    };
    let root = path.first().map_or("", String::as_str);
    if path.len() == 2 && located.generated.contains(root) {
        return false;
    }
    let own = path.len() == 1 || ["crate", "self", "super"].contains(&root);
    if own && located.quiet.contains(name) {
        return false;
    }
    if own && located.reading.contains(name) {
        return true;
    }
    let standard = path.len() == 1 || path.len() == 2 && ["std", "core", "alloc"].contains(&root);
    let quiet = EXPRESSION_MACROS.contains(&name)
        || FORMAT_MACROS.contains(&name)
        || QUIET_STANDARD_MACROS.contains(&name)
        || name == "macro_rules";
    !(standard && quiet && !(path.len() == 1 && located.bound.contains(name)))
}

/// The identifiers of a token tree, `r#` dropped.
fn token_idents(tokens: &TokenStream, out: &mut BTreeSet<String>) {
    for tt in tokens.clone() {
        match tt {
            TokenTree::Ident(i) => {
                let text = i.to_string();
                out.insert(text.strip_prefix("r#").unwrap_or(&text).to_string());
            }
            TokenTree::Group(g) => token_idents(&g.stream(), out),
            _ => {}
        }
    }
}

/// The names a token tree writes after `fn`; `None` when a `fn` is followed
/// by something that is neither an identifier nor a metavariable.
fn written_functions(tokens: &TokenStream, out: &mut Option<BTreeSet<String>>) {
    let tokens: Vec<TokenTree> = tokens.clone().into_iter().collect();
    for (i, t) in tokens.iter().enumerate() {
        match t {
            TokenTree::Group(g) => written_functions(&g.stream(), out),
            TokenTree::Ident(id) if id == "fn" => match tokens.get(i + 1) {
                Some(TokenTree::Ident(name)) => {
                    let text = name.to_string();
                    if let Some(names) = out.as_mut() {
                        names.insert(text.strip_prefix("r#").unwrap_or(&text).to_string());
                    }
                }
                // `fn $name`: the name is one of the call's identifiers.
                Some(TokenTree::Punct(p)) if p.as_char() == '$' => {}
                // `fn(u32) -> u32`, a function pointer type, names nothing.
                Some(TokenTree::Group(g))
                    if g.delimiter() == proc_macro2::Delimiter::Parenthesis => {}
                _ => *out = None,
            },
            _ => {}
        }
    }
}

impl Locating {
    /// Read one file. `origin` names it in a reason; `foreign` is a file of
    /// a dependency, whose `macro_rules!` macros are not the workspace's.
    fn read(&mut self, file: &syn::File, origin: &str, foreign: bool) {
        struct Reader<'l> {
            locating: &'l mut Locating,
            origin: &'l str,
            foreign: bool,
            /// The attributes of the items around the one visited.
            around: Vec<syn::Meta>,
        }
        fn tracked(attrs: &[syn::Attribute]) -> bool {
            attrs.iter().any(|a| {
                let path = a.path();
                if path.is_ident("track_caller") {
                    return true;
                }
                let mut names = BTreeSet::new();
                if path.is_ident("cfg_attr") {
                    token_idents(&quote::ToTokens::to_token_stream(&a.meta), &mut names);
                }
                names.contains("track_caller")
            })
        }
        impl Reader<'_> {
            fn function(
                &mut self,
                attrs: &[syn::Attribute],
                name: &syn::Ident,
                body: Option<&syn::Block>,
            ) {
                if !tracked(attrs) {
                    return;
                }
                let line = name.span().start().line;
                let metas: Vec<syn::Meta> = self
                    .around
                    .iter()
                    .cloned()
                    .chain(attrs.iter().map(|a| a.meta.clone()))
                    .collect();
                self.locating
                    .attributed
                    .push((format!("{}:{line}", self.origin), metas));
                let body = body.map(|b| {
                    let tokens = quote::ToTokens::to_token_stream(b);
                    let mut ids = BTreeSet::new();
                    token_idents(&tokens, &mut ids);
                    let mut calls = Vec::new();
                    macro_calls(&tokens, &mut calls);
                    (ids, calls.into_iter().map(|(p, _)| p).collect())
                });
                self.locating.tracked.push((name.to_string(), body));
            }
            fn enter(&mut self, attrs: &[syn::Attribute]) -> usize {
                self.around.extend(attrs.iter().map(|a| a.meta.clone()));
                attrs.len()
            }
            fn leave(&mut self, mark: usize) {
                self.around.truncate(self.around.len() - mark);
            }
        }
        impl<'ast> Visit<'ast> for Reader<'_> {
            fn visit_item_fn(&mut self, f: &'ast syn::ItemFn) {
                self.function(&f.attrs, &f.sig.ident, Some(&f.block));
                let mark = self.enter(&f.attrs);
                visit::visit_item_fn(self, f);
                self.leave(mark);
            }
            fn visit_impl_item_fn(&mut self, f: &'ast syn::ImplItemFn) {
                self.function(&f.attrs, &f.sig.ident, Some(&f.block));
                let mark = self.enter(&f.attrs);
                visit::visit_impl_item_fn(self, f);
                self.leave(mark);
            }
            fn visit_trait_item_fn(&mut self, f: &'ast syn::TraitItemFn) {
                self.function(&f.attrs, &f.sig.ident, f.default.as_ref());
                let mark = self.enter(&f.attrs);
                visit::visit_trait_item_fn(self, f);
                self.leave(mark);
            }
            fn visit_item_impl(&mut self, i: &'ast syn::ItemImpl) {
                let mark = self.enter(&i.attrs);
                visit::visit_item_impl(self, i);
                self.leave(mark);
            }
            fn visit_item_trait(&mut self, i: &'ast syn::ItemTrait) {
                let mark = self.enter(&i.attrs);
                visit::visit_item_trait(self, i);
                self.leave(mark);
            }
            fn visit_item_mod(&mut self, i: &'ast syn::ItemMod) {
                let mark = self.enter(&i.attrs);
                visit::visit_item_mod(self, i);
                self.leave(mark);
            }
            fn visit_use_rename(&mut self, r: &'ast syn::UseRename) {
                self.locating
                    .renames
                    .push((r.ident.to_string(), r.rename.to_string()));
            }
            fn visit_macro(&mut self, m: &'ast syn::Macro) {
                if let Some(last) = m.path.segments.last() {
                    let mut ids = BTreeSet::new();
                    token_idents(&m.tokens, &mut ids);
                    if self.locating.generator && ids.contains("track_caller") {
                        let line = last.ident.span().start().line;
                        let origin = self.origin;
                        self.locating.unknown.get_or_insert_with(|| {
                            format!("{origin}:{line}: a procedural macro emits #[track_caller]")
                        });
                    }
                    self.locating
                        .invocations
                        .push((last.ident.to_string(), ids));
                }
            }
            fn visit_item_macro(&mut self, i: &'ast syn::ItemMacro) {
                let Some(id) = &i.ident else {
                    self.visit_macro(&i.mac);
                    return;
                };
                let mut body = BTreeSet::new();
                token_idents(&i.mac.tokens, &mut body);
                let mut calls = Vec::new();
                macro_calls(&i.mac.tokens, &mut calls);
                let calls: Vec<Vec<String>> = calls.into_iter().map(|(path, _)| path).collect();
                let mut functions = Some(BTreeSet::new());
                written_functions(&i.mac.tokens, &mut functions);
                if !self.foreign {
                    self.locating
                        .macros
                        .push((id.to_string(), body.clone(), calls.clone()));
                }
                self.locating.every.push(RulesMacro {
                    name: id.to_string(),
                    body,
                    calls,
                    functions,
                });
            }
        }
        Reader {
            locating: self,
            origin,
            foreign,
            around: Vec::new(),
        }
        .visit_file(file);
    }

    /// The names whose call reads its own location, to a fixpoint (see
    /// [`Locating`]). `bound` is the names the workspace binds to a macro.
    fn close(&self, bound: &BTreeSet<String>) -> Located {
        self.closure(bound).0
    }

    /// [`Locating::close`], and the names a dependency's file must mention
    /// to say more: `track_caller`, every reading name (a `use ... as` of
    /// it), and every macro a tracked function's definition goes through
    /// (its `macro_rules!` and its calls).
    fn closure(&self, bound: &BTreeSet<String>) -> (Located, BTreeSet<String>) {
        let base: BTreeSet<String> = ["line", "column", "caller", "caller_location"]
            .map(str::to_string)
            .into_iter()
            .collect();
        let workspace: BTreeSet<String> = self.macros.iter().map(|m| m.0.clone()).collect();
        let visible: BTreeSet<&str> = self.every.iter().map(|m| m.name.as_str()).collect();
        let mut unknown = self.unknown.clone();
        for (place, metas) in &self.attributed {
            if metas.iter().any(|m| !builtin(m, bound)) {
                unknown.get_or_insert_with(|| {
                    format!("{place}: a #[track_caller] function under an attribute macro")
                });
            }
        }
        let mut wanted: BTreeSet<String> = ["track_caller".to_string()].into();
        // A call of a `macro_rules!` macro the figures read (of the
        // workspace or of a dependency, by its name) is judged by the
        // fixpoint, since its name is an identifier of the caller's body;
        // any other call as if no workspace macro read its location.
        let outside = Located {
            quiet: workspace.clone(),
            bound: bound.clone(),
            ..Located::default()
        };
        let foreign = |path: &Vec<String>| {
            path.last().is_some_and(|l| !visible.contains(l.as_str()))
                && locating_call(path, &outside)
        };
        let mut names: BTreeSet<String> = BTreeSet::new();
        for m in &self.every {
            if m.calls.iter().any(foreign) {
                names.insert(m.name.clone());
            }
        }
        for (name, body) in &self.tracked {
            let reads = match body {
                None => true,
                Some((_, calls)) => calls.iter().any(foreign),
            };
            if reads {
                names.insert(name.clone());
            }
        }
        // A macro a tracked body or a read macro calls is looked for.
        let called = self
            .tracked
            .iter()
            .filter_map(|(_, body)| body.as_ref())
            .flat_map(|(_, calls)| calls)
            .chain(self.every.iter().flat_map(|m| &m.calls));
        for path in called {
            if foreign(path) {
                if let Some(last) = path.last().filter(|l| !l.starts_with('$')) {
                    wanted.insert(last.clone());
                }
            }
        }
        // The macros through which a tracked function is defined: those
        // whose body names `track_caller`, those called with it in their
        // tokens, and every macro such a macro calls.
        let mut defining: BTreeSet<&str> = self
            .every
            .iter()
            .filter(|m| m.body.contains("track_caller"))
            .map(|m| m.name.as_str())
            .collect();
        for (name, ids) in &self.invocations {
            if ids.contains("track_caller") {
                defining.insert(name.as_str());
            }
        }
        loop {
            let reached: Vec<&str> = self
                .every
                .iter()
                .filter(|m| defining.contains(m.name.as_str()))
                .flat_map(|m| m.calls.iter().filter_map(|p| p.last()))
                .map(String::as_str)
                .filter(|last| visible.contains(last) && !defining.contains(last))
                .collect();
            if reached.is_empty() {
                break;
            }
            defining.extend(reached);
        }
        for name in &defining {
            wanted.insert((*name).to_string());
            if !visible.contains(name) {
                unknown.get_or_insert_with(|| {
                    format!("the macro {name}! is called with #[track_caller] in its tokens and is no macro_rules! the figures read")
                });
            }
        }
        for m in self
            .every
            .iter()
            .filter(|m| defining.contains(m.name.as_str()))
        {
            if m.functions.is_none() {
                unknown.get_or_insert_with(|| {
                    format!(
                        "the macro {}! writes a #[track_caller] function whose name it builds",
                        m.name
                    )
                });
            }
            for path in &m.calls {
                let last = path.last().map_or("", String::as_str);
                let quiet = !locating_call(path, &Located::default());
                if !visible.contains(last) && !quiet {
                    wanted.insert(last.trim_start_matches('$').to_string());
                    unknown.get_or_insert_with(|| {
                        format!(
                            "the macro {}! writes a #[track_caller] function through {}!, which the figures do not read",
                            m.name,
                            path.join("::")
                        )
                    });
                }
            }
        }
        // `names` are the functions whose call reads (an identifier names
        // one), `macros` the macros whose call reads (a call `name!` names
        // one): a macro's name read as a plain identifier would make every
        // variable of that name read.
        let mut macros: BTreeSet<String> = std::mem::take(&mut names);
        names = macros
            .iter()
            .filter(|n| self.tracked.iter().any(|(t, _)| t == *n))
            .cloned()
            .collect();
        macros.retain(|n| visible.contains(n.as_str()));
        loop {
            let before = names.len() + macros.len();
            let reads: BTreeSet<String> = base.union(&names).cloned().collect();
            let hit = |ids: &BTreeSet<String>, calls: &[Vec<String>]| {
                ids.iter().any(|i| reads.contains(i))
                    || calls
                        .iter()
                        .any(|p| p.last().is_some_and(|l| macros.contains(l)))
            };
            let (mut functions, mut readers): (Vec<String>, Vec<String>) = (Vec::new(), Vec::new());
            for m in &self.every {
                if hit(&m.body, &m.calls) {
                    readers.push(m.name.clone());
                }
            }
            for (name, body) in &self.tracked {
                if body.as_ref().is_some_and(|(ids, calls)| hit(ids, calls)) {
                    functions.push(name.clone());
                }
            }
            for (leaf, alias) in &self.renames {
                if reads.contains(leaf) {
                    functions.push(alias.clone());
                }
                if macros.contains(leaf) {
                    readers.push(alias.clone());
                }
            }
            for m in self
                .every
                .iter()
                .filter(|m| defining.contains(m.name.as_str()))
            {
                let calls: Vec<&BTreeSet<String>> = self
                    .invocations
                    .iter()
                    .filter(|(n, _)| *n == m.name)
                    .map(|(_, ids)| ids)
                    .collect();
                let callers: Vec<&RulesMacro> = self
                    .every
                    .iter()
                    .filter(|e| e.calls.iter().any(|p| p.last() == Some(&m.name)))
                    .collect();
                let reads_here = hit(&m.body, &m.calls)
                    || m.calls.iter().any(foreign)
                    || calls.iter().any(|ids| hit(ids, &[]))
                    || callers.iter().any(|e| hit(&e.body, &e.calls));
                if reads_here {
                    functions.extend(m.functions.iter().flatten().cloned());
                    functions.extend(calls.into_iter().flatten().cloned());
                    functions.extend(callers.into_iter().flat_map(|e| e.body.iter().cloned()));
                }
            }
            names.extend(functions);
            macros.extend(readers);
            if names.len() + macros.len() == before {
                break;
            }
        }
        for name in UNSPELLED {
            if names.contains(name) {
                unknown.get_or_insert_with(|| {
                    format!("a #[track_caller] {name} reads its caller, and a dereference the source does not spell calls it")
                });
            }
        }
        wanted.extend(names.iter().cloned());
        wanted.extend(macros.iter().cloned());
        let quiet = workspace.difference(&macros).cloned().collect();
        names.extend(workspace.intersection(&macros).cloned());
        (
            Located {
                reading: names,
                quiet,
                bound: bound.clone(),
                generated: BTreeSet::new(),
                calls: unknown,
            },
            wanted,
        )
    }
}

/// The words of a line, as identifiers spell them.
fn words(line: &str) -> impl Iterator<Item = &str> {
    line.split(|c: char| !(c.is_alphanumeric() || c == '_'))
        .filter(|w| !w.is_empty())
}

/// Whether a line invokes the macro `name` (`name!`, spaces allowed).
fn invokes(line: &str, name: &str) -> bool {
    line.match_indices(name).any(|(i, _)| {
        let before = line[..i].chars().next_back();
        let rest = line[i + name.len()..].trim_start();
        before.is_none_or(|c| !(c.is_alphanumeric() || c == '_')) && rest.starts_with('!')
    })
}

/// The lines of a text whose value reads its own column (`column!()`,
/// `Location::caller()`, a call of a `#[track_caller]` function or of a
/// macro that reads one, all of `located.reading`, or of a macro the
/// figures do not read, [`locating_call`]) and the lines whose value reads
/// its own line (those, and `line!()`). A rewrite earlier on a line of the
/// first set moves the column it reads; a layout that moves a line of the
/// second changes the line it reads. A reading method the language calls
/// for an operator ([`SUGAR`]) is called on each line that holds its
/// token; while `located.calls` says a call of any name may read, each line
/// that calls a function or a method reads its column.
///
/// They are read from the text's tokens, so a comment or a string that
/// spells such a name reads nothing (a doc comment is a string). A text the
/// lexer refuses is read line by line, every word counted and every line
/// with a `!` taken to call a macro (every line, while an operator or any
/// call may read).
fn location_lines(text: &str, located: &Located) -> (BTreeSet<usize>, BTreeSet<usize>) {
    let mut columns = BTreeSet::new();
    let mut lines = BTreeSet::new();
    let sugar: BTreeSet<&str> = SUGAR
        .iter()
        .filter(|(name, _)| located.reading.contains(*name))
        .map(|(_, token)| *token)
        .collect();
    if let Ok(tokens) = text.parse::<TokenStream>() {
        struct Walk<'w> {
            located: &'w Located,
            sugar: &'w BTreeSet<&'w str>,
            columns: &'w mut BTreeSet<usize>,
        }
        impl Walk<'_> {
            fn walk(&mut self, tokens: TokenStream) {
                let tokens: Vec<TokenTree> = tokens.into_iter().collect();
                for (i, t) in tokens.iter().enumerate() {
                    match t {
                        TokenTree::Group(g) => {
                            use proc_macro2::Delimiter;
                            let before = i.checked_sub(1).map(|k| &tokens[k]);
                            let call = g.delimiter() == Delimiter::Parenthesis
                                && match before {
                                    Some(TokenTree::Ident(id)) => {
                                        let defined = i >= 2
                                            && matches!(&tokens[i - 2], TokenTree::Ident(f) if f == "fn");
                                        !defined && !KEYWORDS.contains(&id.to_string().as_str())
                                    }
                                    Some(TokenTree::Punct(p)) => p.as_char() == '>',
                                    Some(TokenTree::Group(_)) => true,
                                    _ => false,
                                };
                            let indexed =
                                g.delimiter() == Delimiter::Bracket && self.sugar.contains("[");
                            if call && self.located.calls.is_some() || indexed {
                                self.columns.insert(g.span_open().start().line);
                            }
                            self.walk(g.stream());
                        }
                        TokenTree::Ident(id) => {
                            let text = id.to_string();
                            let name = text.strip_prefix("r#").unwrap_or(&text);
                            if name == "caller"
                                || self.located.reading.contains(name)
                                || self.sugar.contains(name)
                            {
                                self.columns.insert(id.span().start().line);
                            }
                        }
                        TokenTree::Punct(p) => {
                            if self.sugar.contains(p.as_char().to_string().as_str()) {
                                self.columns.insert(p.span().start().line);
                            }
                        }
                        TokenTree::Literal(_) => {}
                    }
                }
            }
        }
        Walk {
            located,
            sugar: &sugar,
            columns: &mut columns,
        }
        .walk(tokens.clone());
        let mut calls = Vec::new();
        macro_calls(&tokens, &mut calls);
        for (path, at) in calls {
            let line_only = path.last().is_some_and(|n| n == "line")
                && (path.len() == 1 || ["std", "core"].contains(&path[0].as_str()))
                && !located.bound.contains("line");
            if line_only {
                lines.insert(at);
            } else if locating_call(&path, located) {
                columns.insert(at);
            }
        }
        lines.extend(columns.iter().copied());
        return (columns, lines);
    }
    let every = located.calls.is_some() || !sugar.is_empty();
    for (i, l) in text.lines().enumerate() {
        let column = every
            || l.contains('!')
            || words(l).any(|w| w == "caller" || located.reading.contains(w));
        if column {
            columns.insert(i + 1);
        }
        if column || invokes(l, "line") {
            lines.insert(i + 1);
        }
    }
    (columns, lines)
}

/// One file to read for sites.
#[derive(Clone)]
struct Source {
    rel: String,
    package: String,
    target: String,
    /// The target's kind: `lib`, `bin`, `test`, `bench`, `example` or
    /// `build` (a build script).
    kind: String,
    module: String,
    test: bool,
    edition: String,
    /// The names the package binds the generated package under, by the
    /// kind of dependency (`normal`, `dev`, `build`).
    depends: BTreeMap<String, BTreeSet<String>>,
    /// The names other crates are bound under in the package: its other
    /// dependencies, and `extern crate x as name;` items.
    taken: BTreeSet<String>,
}

impl Source {
    /// The names a rewritten site of this file is read by.
    fn krates(&self, generated: &str) -> BTreeSet<String> {
        let mut names: BTreeSet<String> = self.depends.values().flatten().cloned().collect();
        if names.is_empty() {
            names.insert(generated.replace('-', "_"));
        }
        names
    }
}

/// The library root directory of a package outside the workspace, and
/// whether it is a procedural macro crate.
type Outside = (PathBuf, bool);

/// How a package binds its dependencies' crates.
#[derive(Clone, Default)]
struct Binding {
    depends: BTreeMap<String, BTreeSet<String>>,
    taken: BTreeSet<String>,
}

/// The names each workspace package binds its dependencies under, by
/// `cargo metadata`'s resolved graph (each edge names the extern crate as
/// the package's code sees it: a rename, or the library's own name); when
/// the graph cannot be read offline at the locked versions, by the
/// manifest's `rename`, or the dependency's name with `-` read as `_`. The
/// generated package is a path dependency of the given name. Also the
/// directory of the library root of every package of the resolved graph
/// that is not a member (registry crates and path dependencies outside the
/// workspace: what a member's code can call; their tests, examples and
/// binaries are no part of it), or `None` when the graph cannot be read.
fn bindings(
    root: &Path,
    plain: &serde_json::Value,
    generated: &str,
) -> (BTreeMap<String, Binding>, Option<Vec<Outside>>) {
    use serde_json::Value;
    let mut out: BTreeMap<String, Binding> = BTreeMap::new();
    let cargo = std::env::var_os("CARGO").unwrap_or_else(|| "cargo".into());
    let resolved = std::process::Command::new(cargo)
        .args(["metadata", "--format-version", "1", "--offline", "--locked"])
        .current_dir(root)
        .output()
        .ok()
        .filter(|o| o.status.success())
        .and_then(|o| serde_json::from_slice::<Value>(&o.stdout).ok());
    let kind_of = |k: &Value| k.as_str().unwrap_or("normal").to_string();
    if let Some(meta) = resolved {
        let packages: BTreeMap<&str, (&str, bool)> = meta
            .get("packages")
            .and_then(Value::as_array)
            .into_iter()
            .flatten()
            .filter_map(|p| {
                let id = p.get("id")?.as_str()?;
                let name = p.get("name")?.as_str()?;
                Some((id, (name, p.get("source").is_none_or(Value::is_null))))
            })
            .collect();
        let members: BTreeSet<&str> = meta
            .get("workspace_members")
            .and_then(Value::as_array)
            .into_iter()
            .flatten()
            .filter_map(Value::as_str)
            .collect();
        let nodes = meta
            .get("resolve")
            .and_then(|r| r.get("nodes"))
            .and_then(Value::as_array);
        for node in nodes.into_iter().flatten() {
            let Some(id) = node.get("id").and_then(Value::as_str) else {
                continue;
            };
            let Some((name, _)) = packages.get(id).filter(|_| members.contains(id)) else {
                continue;
            };
            let entry = out.entry((*name).to_string()).or_default();
            for dep in node
                .get("deps")
                .and_then(Value::as_array)
                .into_iter()
                .flatten()
            {
                let extern_name = dep.get("name").and_then(Value::as_str).unwrap_or_default();
                let pkg = dep.get("pkg").and_then(Value::as_str).unwrap_or_default();
                let is_generated = packages
                    .get(pkg)
                    .is_some_and(|(n, path)| *n == generated && *path);
                for k in dep
                    .get("dep_kinds")
                    .and_then(Value::as_array)
                    .into_iter()
                    .flatten()
                {
                    let kind = kind_of(k.get("kind").unwrap_or(&Value::Null));
                    if is_generated {
                        entry
                            .depends
                            .entry(kind)
                            .or_default()
                            .insert(extern_name.to_string());
                    } else {
                        entry.taken.insert(extern_name.to_string());
                    }
                }
            }
        }
        let outside = meta
            .get("packages")
            .and_then(Value::as_array)
            .into_iter()
            .flatten()
            .filter(|p| {
                p.get("id")
                    .and_then(Value::as_str)
                    .is_some_and(|id| !members.contains(id))
            })
            .flat_map(|p| {
                p.get("targets")
                    .and_then(Value::as_array)
                    .into_iter()
                    .flatten()
            })
            .filter(|t| {
                t.get("kind")
                    .and_then(Value::as_array)
                    .into_iter()
                    .flatten()
                    .filter_map(Value::as_str)
                    .all(|k| !["bin", "test", "bench", "example", "custom-build"].contains(&k))
            })
            .filter_map(|t| {
                let generator = t
                    .get("kind")
                    .and_then(Value::as_array)
                    .into_iter()
                    .flatten()
                    .any(|k| k.as_str() == Some("proc-macro"));
                let root = crate::ingest::parent(Path::new(t.get("src_path")?.as_str()?));
                Some((root, generator))
            })
            .collect::<BTreeSet<Outside>>()
            .into_iter()
            .collect();
        return (out, Some(outside));
    }
    // Without the resolved graph the packages outside the workspace are
    // known only when there are none: every dependency is a member's path.
    let members: BTreeSet<PathBuf> = plain
        .get("packages")
        .and_then(Value::as_array)
        .into_iter()
        .flatten()
        .filter_map(|p| p.get("manifest_path")?.as_str())
        .filter_map(|m| crate::ingest::parent(Path::new(m)).canonicalize().ok())
        .collect();
    let mut inside = true;
    for p in plain
        .get("packages")
        .and_then(Value::as_array)
        .into_iter()
        .flatten()
    {
        let Some(name) = p.get("name").and_then(Value::as_str) else {
            continue;
        };
        inside &= p
            .get("dependencies")
            .and_then(Value::as_array)
            .into_iter()
            .flatten()
            .all(|dep| {
                dep.get("path")
                    .and_then(Value::as_str)
                    .and_then(|d| Path::new(d).canonicalize().ok())
                    .is_some_and(|d| members.contains(&d))
            });
        let entry = out.entry(name.to_string()).or_default();
        for dep in p
            .get("dependencies")
            .and_then(Value::as_array)
            .into_iter()
            .flatten()
        {
            let dep_name = dep.get("name").and_then(Value::as_str).unwrap_or_default();
            let bound = dep
                .get("rename")
                .and_then(Value::as_str)
                .map_or_else(|| dep_name.replace('-', "_"), str::to_string);
            let is_generated =
                dep_name == generated && dep.get("path").is_some_and(Value::is_string);
            let kind = kind_of(dep.get("kind").unwrap_or(&Value::Null));
            if is_generated {
                entry.depends.entry(kind).or_default().insert(bound);
            } else {
                entry.taken.insert(bound);
            }
        }
    }
    (out, inside.then(Vec::new))
}

/// The targets of a package as `cargo metadata` lists them, build scripts
/// included: name, kind, root file.
fn meta_targets(meta: &serde_json::Value, package: &str) -> Vec<(String, String, PathBuf)> {
    use serde_json::Value;
    let mut out = Vec::new();
    for p in meta
        .get("packages")
        .and_then(Value::as_array)
        .into_iter()
        .flatten()
        .filter(|p| p.get("name").and_then(Value::as_str) == Some(package))
    {
        for t in p
            .get("targets")
            .and_then(Value::as_array)
            .into_iter()
            .flatten()
        {
            let kinds: Vec<&str> = t
                .get("kind")
                .and_then(Value::as_array)
                .into_iter()
                .flatten()
                .filter_map(Value::as_str)
                .collect();
            let kind = if kinds.contains(&"custom-build") {
                "build"
            } else if kinds
                .iter()
                .any(|k| ["lib", "rlib", "cdylib", "staticlib", "dylib", "proc-macro"].contains(k))
            {
                "lib"
            } else if let Some(k) = kinds.first() {
                k
            } else {
                continue;
            };
            let name = t.get("name").and_then(Value::as_str).unwrap_or_default();
            let src = t
                .get("src_path")
                .and_then(Value::as_str)
                .unwrap_or_default();
            out.push((name.to_string(), kind.to_string(), PathBuf::from(src)));
        }
    }
    out
}

/// The paths `include!("..")` names in a file, as written.
fn includes(file: &syn::File) -> Vec<String> {
    struct Inc(Vec<String>);
    impl<'ast> Visit<'ast> for Inc {
        fn visit_macro(&mut self, m: &'ast syn::Macro) {
            if m.path.segments.last().is_some_and(|s| s.ident == "include") {
                if let Ok(p) = m.parse_body::<syn::LitStr>() {
                    self.0.push(p.value());
                }
            }
        }
    }
    let mut inc = Inc(Vec::new());
    inc.visit_file(file);
    inc.0
}

/// A path relative to the workspace root, as the register writes it; the
/// path itself when it lies outside.
fn relative(root: &Path, path: &Path) -> String {
    path.strip_prefix(root)
        .unwrap_or(path)
        .to_string_lossy()
        .replace('\\', "/")
}

/// The module path a file found by the module tree is keyed by: its path
/// from the target root's directory (or else the package's, or else the
/// workspace's), without `.rs` and `mod`.
fn module_of(file: &Path, target_root: &Path, package_dir: &Path, root: &Path) -> String {
    if file == target_root {
        return String::new();
    }
    let base = crate::ingest::parent(target_root);
    let rel = [base.as_path(), package_dir, root]
        .iter()
        .find_map(|b| file.strip_prefix(b).ok())
        .unwrap_or(file);
    let text = rel.to_string_lossy().replace('\\', "/");
    let text = text.strip_suffix(".rs").unwrap_or(&text);
    let text = text.strip_suffix("/mod").unwrap_or(text);
    text.trim_start_matches('/').replace('/', "::")
}

/// The workspace's source files: every file the tool's reader assigns to a
/// target, and every file the compiler reads from a target root (build
/// scripts included) by its module tree (`mod name;`, `#[path]`, wherever
/// the file lies, and `include!`). The generated package's own files are
/// judged at its register, never read for sites.
/// A workspace's root, its files, the files that do not parse, and the
/// directories of the packages outside it that its build resolves
/// ([`bindings`]).
type Sources = (PathBuf, Vec<Source>, Vec<String>, Option<Vec<Outside>>);

fn sources(root: &Path, generated: &str) -> Result<Sources, UorustError> {
    use crate::facts::TargetKind;
    use crate::ingest::{declared_files, normal, parent, ModFile};
    let root = root.canonicalize().map_err(|e| io(root, e))?;
    let (workspace, _) = crate::ingest::workspace(&root, None)?;
    let meta = crate::ingest::metadata(&root)?;
    let (bound, dependencies) = bindings(&root, &meta, generated);
    let mut out: Vec<Source> = Vec::new();
    let mut unparsed = Vec::new();
    for p in &workspace.packages {
        if p.name == generated {
            continue;
        }
        let binding = bound.get(&p.name).cloned().unwrap_or_default();
        let package_dir = root.join(&p.dir);
        // Each file once, by its path: the index of its row.
        let mut have: BTreeMap<PathBuf, Option<usize>> = BTreeMap::new();
        for f in &p.files {
            let path = root.join(&f.rel);
            if let Some(e) = &f.parse_error {
                unparsed.push(e.clone());
                have.insert(path, None);
                continue;
            }
            let kind = match p.targets[f.target].kind {
                TargetKind::Lib => "lib",
                TargetKind::Bin => "bin",
                TargetKind::Test => "test",
                TargetKind::Example => "example",
                TargetKind::Bench => "bench",
            };
            have.insert(path, Some(out.len()));
            out.push(Source {
                rel: f.rel.clone(),
                package: p.name.clone(),
                target: p.targets[f.target].name.clone(),
                kind: kind.to_string(),
                module: f.module.clone(),
                test: f.test,
                edition: p.edition.clone(),
                depends: binding.depends.clone(),
                taken: binding.taken.clone(),
            });
        }
        let mut added: BTreeSet<usize> = BTreeSet::new();
        for (target, kind, src) in meta_targets(&meta, &p.name) {
            let mut todo = vec![ModFile {
                dir: parent(&src),
                file: src.clone(),
                own: None,
                test: false,
            }];
            let mut seen: BTreeSet<(PathBuf, bool)> = BTreeSet::new();
            while let Some(at) = todo.pop() {
                if !seen.insert((at.file.clone(), at.test)) {
                    continue;
                }
                let Ok(text) = std::fs::read_to_string(&at.file) else {
                    continue;
                };
                let tree = match syn::parse_file(&text) {
                    Ok(tree) => tree,
                    Err(e) => {
                        if !have.contains_key(&at.file) {
                            unparsed.push(format!("{}: {e}", relative(&root, &at.file)));
                            have.insert(at.file.clone(), None);
                        }
                        continue;
                    }
                };
                let test = at.test || kind == "test" || kind == "bench";
                match have.get(&at.file) {
                    Some(Some(i)) if !test && added.contains(i) => out[*i].test = false,
                    Some(_) => {}
                    None => {
                        have.insert(at.file.clone(), Some(out.len()));
                        added.insert(out.len());
                        out.push(Source {
                            rel: relative(&root, &at.file),
                            package: p.name.clone(),
                            target: target.clone(),
                            kind: kind.clone(),
                            module: module_of(&at.file, &src, &package_dir, &root),
                            test,
                            edition: p.edition.clone(),
                            depends: binding.depends.clone(),
                            taken: binding.taken.clone(),
                        });
                    }
                }
                let mut found = Vec::new();
                declared_files(&tree.items, &at.dir, at.own.as_deref(), at.test, &mut found);
                todo.extend(found);
                for inc in includes(&tree) {
                    let file = normal(&parent(&at.file).join(inc));
                    todo.push(ModFile {
                        dir: parent(&file),
                        file,
                        own: None,
                        test: at.test,
                    });
                }
            }
        }
        // `extern crate x as name;` binds `name` in the extern prelude.
        let renamed: BTreeSet<String> = out
            .iter()
            .filter(|s| s.package == p.name)
            .filter_map(|s| std::fs::read_to_string(root.join(&s.rel)).ok())
            .filter_map(|t| syn::parse_file(&t).ok())
            .flat_map(|t| t.items)
            .filter_map(|i| match i {
                syn::Item::ExternCrate(e) => e.rename.map(|(_, r)| r.to_string()),
                _ => None,
            })
            .collect();
        for s in out.iter_mut().filter(|s| s.package == p.name) {
            s.taken.extend(renamed.iter().cloned());
        }
    }
    Ok((root, out, unparsed, dependencies))
}

/// What one file's walk read: its sites, the doc texts it includes from
/// other files, and what it could not read.
struct FileSites {
    sites: Vec<Site>,
    included: Vec<(String, String)>,
    unread: Vec<String>,
}

/// Sites from the walk's raw finds: sorted, one per span, each keyed by its
/// package, target, module, item, literal and ordinal among the sites of
/// that literal in that item.
fn keyed(mut raws: Vec<Raw>, source: &Source, lines: &Lines<'_>) -> Vec<Site> {
    raws.sort_by_key(|r| r.bytes);
    raws.dedup_by_key(|r| r.bytes);
    let mut ordinal: BTreeMap<(String, String), usize> = BTreeMap::new();
    let module = if source.module.is_empty() {
        String::new()
    } else {
        format!("::{}", source.module)
    };
    raws.into_iter()
        .map(|r| {
            let n = ordinal
                .entry((r.item.clone(), r.literal.clone()))
                .or_default();
            let item = if r.item.is_empty() {
                String::new()
            } else {
                format!("::{}", r.item)
            };
            let key = format!(
                "{}/{}{module}{item}:{}:{n}",
                source.package, source.target, r.literal
            );
            *n += 1;
            let start = lines.at(r.bytes.0);
            let end = lines.at(r.bytes.1);
            Site {
                key,
                file: source.rel.clone(),
                start: (start.line, start.column),
                end: (end.line, end.column),
                literal: r.literal,
                place: r.place,
                stratum: None,
                test: r.test,
                form: r.form,
                bytes: r.bytes,
            }
        })
        .collect()
}

/// The sites of one file's text: every numeric literal, counted or not, in
/// source order, with keys made unique per item and literal.
fn file_sites(
    text: &str,
    source: &Source,
    generated: &str,
    figures: &BTreeMap<String, String>,
    shadowed: &BTreeSet<String>,
) -> Option<FileSites> {
    let tree = syn::parse_file(text).ok()?;
    let lines = Lines::new(text);
    let krates = source.krates(generated);
    let mut walk = Walk {
        lines: &lines,
        krates: &krates,
        figures,
        shadowed,
        edition: &source.edition,
        doctested: source.kind == "lib",
        items: Vec::new(),
        test: source.test,
        frozen: None,
        raws: Vec::new(),
        included: Vec::new(),
        unread: Vec::new(),
    };
    for a in &tree.attrs {
        walk.visit_attribute(a);
    }
    walk.docs(&tree.attrs);
    for item in &tree.items {
        walk.visit_item(item);
    }
    let Walk {
        raws,
        included,
        unread,
        ..
    } = walk;
    Some(FileSites {
        sites: keyed(raws, source, &lines),
        included,
        unread,
    })
}

/// The doc-test sites of a doc text read from a file (`#[doc =
/// include_str!(..)]`): the file is the source of their bytes, the item
/// that includes it their item.
fn included_sites(text: &str, source: &Source, item: &str) -> (Vec<Site>, Vec<String>) {
    let lines = Lines::new(text);
    let (found, unlexed) = doc_literals(&lines_at(text, 0));
    let item = if item.is_empty() {
        "doc".to_string()
    } else {
        format!("{item}::doc")
    };
    let raws = found
        .into_iter()
        .map(|(a, b, literal)| Raw {
            item: item.clone(),
            literal,
            place: Place::DocTest,
            test: true,
            form: Form::Literal,
            bytes: (a, b),
        })
        .collect();
    let unread = unlexed
        .into_iter()
        .map(|at| {
            format!(
                "{}: the doc test at line {} does not lex",
                source.rel,
                lines.at(at).line
            )
        })
        .collect();
    (keyed(raws, source, &lines), unread)
}

/// Read into `locating` the files of the packages outside the workspace
/// (`dependencies`, [`bindings`]) that mention a name it still wants
/// ([`Locating::closure`]), to a fixpoint: a file that mentions none of
/// them defines no tracked function, renames no reading one and writes
/// none through a macro. A wanted file that does not parse, or a graph that
/// cannot be read, leaves the reading unknown.
fn read_dependencies(
    locating: &mut Locating,
    dependencies: Option<&[Outside]>,
    bound: &BTreeSet<String>,
) {
    fn rust_files(dir: &Path, out: &mut Vec<PathBuf>) {
        let Ok(entries) = std::fs::read_dir(dir) else {
            return;
        };
        let mut entries: Vec<PathBuf> = entries.filter_map(|e| Some(e.ok()?.path())).collect();
        entries.sort();
        for path in entries {
            let name = path.file_name().and_then(|n| n.to_str()).unwrap_or("");
            if path.is_dir() {
                if name != "target" && !name.starts_with('.') {
                    rust_files(&path, out);
                }
            } else if name.ends_with(".rs") {
                out.push(path);
            }
        }
    }
    let Some(dirs) = dependencies else {
        locating.unknown.get_or_insert_with(|| {
            "the dependency graph cannot be resolved offline at the locked versions, so the dependencies' sources are unread".to_string()
        });
        return;
    };
    let mut files = Vec::new();
    let mut generators: BTreeSet<PathBuf> = BTreeSet::new();
    for (dir, generator) in dirs {
        let start = files.len();
        rust_files(dir, &mut files);
        if *generator {
            generators.extend(files[start..].iter().cloned());
        }
    }
    let mut searched: BTreeSet<String> = BTreeSet::new();
    let mut read: BTreeSet<usize> = BTreeSet::new();
    loop {
        let (_, wanted) = locating.closure(bound);
        let new: Vec<String> = wanted.difference(&searched).cloned().collect();
        if new.is_empty() {
            return;
        }
        searched.extend(new.iter().cloned());
        for (i, path) in files.iter().enumerate() {
            if read.contains(&i) {
                continue;
            }
            let Ok(text) = std::fs::read_to_string(path) else {
                continue;
            };
            if !new.iter().any(|w| text.contains(w.as_str())) {
                continue;
            }
            read.insert(i);
            let origin = path.display().to_string();
            match syn::parse_file(&text) {
                Ok(tree) => {
                    locating.generator = generators.contains(path);
                    locating.read(&tree, &origin, true);
                    locating.generator = false;
                }
                Err(_) => {
                    locating
                        .unknown
                        .get_or_insert_with(|| format!("{origin}: the file does not parse"));
                }
            }
        }
    }
}

/// A workspace as the figures read it: its files with their texts, the
/// names that may stand for a workspace macro, and the names whose call
/// reads its own location.
struct Loaded {
    root: PathBuf,
    files: Vec<(Source, String)>,
    unparsed: Vec<String>,
    shadowed: BTreeSet<String>,
    located: Located,
}

fn load(root: &Path, rules: &Rules) -> Result<Loaded, UorustError> {
    let (root, sources, unparsed, dependencies) = sources(root, &rules.package.name)?;
    let local: BTreeSet<String> = sources
        .iter()
        .map(|f| f.package.replace('-', "_"))
        .collect();
    let mut shadowed = BTreeSet::new();
    let mut locating = Locating::default();
    let mut files = Vec::new();
    let (mut foreign_glob, mut preludeless) = (false, false);
    for f in sources {
        let path = root.join(&f.rel);
        let text = std::fs::read_to_string(&path).map_err(|e| io(&path, e))?;
        match syn::parse_file(&text) {
            Ok(tree) => {
                foreign_glob |= bound_macro_names(&tree, &local, &mut shadowed);
                preludeless |= without_prelude(&tree);
                locating.read(&tree, &f.rel, false);
            }
            Err(_) => {
                let reason = format!("{}: the file does not parse", f.rel);
                locating.unknown.get_or_insert(reason);
            }
        }
        files.push((f, text));
    }
    // A glob of another crate binds a standard name only where no prelude
    // binds it (`bound_macro_names`).
    if foreign_glob && preludeless {
        every_standard_name(&mut shadowed);
    }
    // A dependency bound as `std`, `core` or `alloc` makes those paths the
    // workspace's own: no name is then the standard library's for sure.
    let standard = ["std", "core", "alloc"];
    if files
        .iter()
        .any(|(f, _)| standard.iter().any(|n| f.taken.contains(*n)))
    {
        every_standard_name(&mut shadowed);
        shadowed.extend(standard.map(str::to_string));
    }
    read_dependencies(&mut locating, dependencies.as_deref(), &shadowed);
    let mut located = locating.close(&shadowed);
    located.generated = files
        .iter()
        .flat_map(|(f, _)| f.depends.values().flatten().cloned())
        .chain([rules.package.name.replace('-', "_")])
        .collect();
    Ok(Loaded {
        root,
        files,
        unparsed,
        shadowed,
        located,
    })
}

/// Read the register of a workspace: its figures (`figures`, the rows a
/// register already holds) and every counted site as the source holds it.
pub fn read(root: &Path, rules: &Rules, figures: Vec<Figure>) -> Result<Register, UorustError> {
    let loaded = load(root, rules)?;
    read_loaded(&loaded, rules, figures)
}

fn read_loaded(
    loaded: &Loaded,
    rules: &Rules,
    figures: Vec<Figure>,
) -> Result<Register, UorustError> {
    use crate::ingest::{normal, parent};
    let values: BTreeMap<String, String> = figures
        .iter()
        .map(|f| (f.name.clone(), f.value.clone()))
        .collect();
    let mut register = Register {
        figures,
        unparsed: loaded.unparsed.clone(),
        ..Register::default()
    };
    // Each doc text a file includes, read once, from the first file that
    // includes it.
    let mut included_once: BTreeSet<PathBuf> = BTreeSet::new();
    for (f, text) in &loaded.files {
        let Some(read) = file_sites(text, f, &rules.package.name, &values, &loaded.shadowed) else {
            continue;
        };
        register
            .unread
            .extend(read.unread.iter().map(|u| format!("{}: {u}", f.rel)));
        let mut parts = vec![(f.rel.clone(), read.sites)];
        for (path, item) in &read.included {
            let file = normal(&parent(&loaded.root.join(&f.rel)).join(path));
            if !included_once.insert(file.clone()) {
                continue;
            }
            let doc = std::fs::read_to_string(&file).map_err(|e| io(&file, e))?;
            let mut source = f.clone();
            source.rel = relative(&loaded.root, &file);
            let (sites, unread) = included_sites(&doc, &source, item);
            register.unread.extend(unread);
            parts.push((source.rel, sites));
        }
        for (rel, sites) in parts {
            let stratum = stratum_of(&rel, rules);
            if stratum.is_some_and(|s| s.exempt) {
                continue;
            }
            let counted: Vec<Site> = sites
                .into_iter()
                .filter(|s| rules.count_tests || !s.test)
                .filter(|s| s.form != Form::Literal || !exempt(&s.literal, rules))
                .map(|mut s| {
                    s.stratum = stratum.map(|st| st.name.clone());
                    s
                })
                .collect();
            if stratum.is_none() && !counted.is_empty() {
                register.unstratified.push(rel.clone());
            }
            register.sites.extend(counted);
        }
    }
    Ok(register)
}

/// What [`extract`] did.
#[derive(Clone, Debug)]
pub struct Extracted {
    /// The register's counts.
    pub counts: Counts,
    /// Site keys the figures listed that no site has any more: dropped
    /// from their figures, each with its figure.
    pub vanished: Vec<String>,
}

/// Write the register of a workspace: the figure rows the register at
/// `register` holds, with only the site keys the source still has, and
/// every counted site.
pub fn extract(root: &Path, rules: &Path, register: &Path) -> Result<Extracted, UorustError> {
    let (rules_v, digest) = read_rules(rules)?;
    let figures = read_figures(register)?;
    let mut reg = read(root, &rules_v, figures)?;
    let keys: BTreeSet<String> = reg.sites.iter().map(|s| s.key.clone()).collect();
    let mut vanished = Vec::new();
    for f in &mut reg.figures {
        f.sites.retain(|k| {
            let kept = keys.contains(k);
            if !kept {
                vanished.push(format!("{}: {k}", f.name));
            }
            kept
        });
    }
    std::fs::write(register, reg.render(&digest)).map_err(|e| io(register, e))?;
    Ok(Extracted {
        counts: reg.counts(),
        vanished,
    })
}

/// The generated package's files, by path relative to its directory, and
/// the LexLean module that states the same figures.
pub fn generate(rules: &Rules, register: &Register) -> (BTreeMap<String, String>, String) {
    let digest = register.figures_digest();
    let header = format!("{GENERATED} from the figure register (figures sha256 {digest})");
    let mut manifest = format!("# {header}\n[package]\n");
    let _ = writeln!(manifest, "name = {}", quote(&rules.package.name));
    let _ = writeln!(manifest, "version = {}", quote(&rules.package.version));
    let _ = writeln!(manifest, "edition = {}", quote(&rules.package.edition));
    if let Some(l) = &rules.package.license {
        let _ = writeln!(manifest, "license = {}", quote(l));
    }
    manifest.push_str("publish = false\n\n[dependencies]\n");
    let mut lib = format!("// {header}\n");
    lib.push_str(
        "//! The workspace's figures: one macro per figure, which expands to the\n\
         //! literal token the register states, and a typed constant where a\n\
         //! range pattern needs a path.\n\n#![no_std]\n",
    );
    let ranged: BTreeSet<&str> = register
        .sites
        .iter()
        .filter(|s| s.place == Place::RangeBound)
        .filter_map(|s| {
            register
                .figures
                .iter()
                .find(|f| f.sites.contains(&s.key))
                .map(|f| f.name.as_str())
        })
        .collect();
    for f in &register.figures {
        let doc = if f.home.is_empty() {
            "No home is stated yet.".to_string()
        } else {
            format!("{}: {}", f.home, f.cites)
        };
        let _ = write!(
            lib,
            "\n/// {doc}\n#[macro_export]\nmacro_rules! {} {{\n    () => {{\n        {}\n    }};\n}}\n",
            f.name, f.value
        );
        if ranged.contains(f.name.as_str()) {
            if let Some(ty) = constant_type(f) {
                let _ = write!(
                    lib,
                    "\n/// The figure `{}` where a range pattern needs a path.\npub const {}: {ty} = {};\n",
                    f.name,
                    constant_name(&f.name),
                    f.value
                );
            }
        }
    }
    let files = [
        ("Cargo.toml".to_string(), manifest),
        ("src/lib.rs".to_string(), lib),
    ]
    .into();
    (files, lexlean_module(register))
}

/// The type of a figure's typed constant: its suffix, or the type its row
/// states.
fn constant_type(f: &Figure) -> Option<String> {
    let suffix = match syn::parse_str::<syn::Lit>(&f.value).ok()? {
        syn::Lit::Int(i) => i.suffix().to_string(),
        syn::Lit::Float(x) => x.suffix().to_string(),
        _ => return None,
    };
    if !suffix.is_empty() {
        return Some(suffix);
    }
    (!f.ty.is_empty()).then(|| f.ty.clone())
}

/// The LexLean module of the figures: an integer figure is the natural
/// number its literal denotes; a float figure is the exact decimal its
/// literal spells, as a significand and a power of ten, since an unsuffixed
/// float literal's width is the one inference gives it and the decimal is
/// what every width rounds from.
fn lexlean_module(register: &Register) -> String {
    let mut out = "\\begin{lexlean}{Figures}\n\\useglossary{lexlean.std.nat@1.2.0}\n\
                   \\useglossary{uorust.titles@1.0.0}\n\\title{Workspace figures}\n\
                   \\begin{semanticmodule}\n"
        .to_string();
    let mut first = true;
    let mut def = |out: &mut String, name: String, result: &str, body: String| {
        if !first {
            out.push('\n');
        }
        first = false;
        let line =
            format!("definition{{name: {name}, parameters: [], result: {result}, body: {body}}}");
        if line.chars().count() <= LEXLEAN_WIDTH {
            out.push_str(&line);
            out.push('\n');
        } else {
            let _ = write!(
                out,
                "definition{{\n  name: {name},\n  parameters: [],\n  result: {result},\n  body: {body}\n}}\n"
            );
        }
    };
    for f in &register.figures {
        let name = format!("figure_{}", f.name);
        match syn::parse_str::<syn::Lit>(&f.value) {
            Ok(syn::Lit::Int(i)) => {
                if let Ok(v) = i.base10_parse::<u128>() {
                    def(&mut out, name, "Nat", v.to_string());
                }
            }
            Ok(syn::Lit::Float(x)) => {
                if let Some((significand, exponent)) = decimal(x.base10_digits()) {
                    def(&mut out, format!("{name}_significand"), "Nat", significand);
                    def(
                        &mut out,
                        format!("{name}_exponent"),
                        "Int",
                        format!("({exponent} : Int)"),
                    );
                }
            }
            _ => {}
        }
    }
    out.push_str("\\end{semanticmodule}\n\\end{lexlean}\n");
    out
}

/// The exact decimal a float literal's digits spell: significand and power
/// of ten, the significand without leading zeros.
fn decimal(digits: &str) -> Option<(String, i64)> {
    let (mantissa, exp) = match digits.find(['e', 'E']) {
        Some(i) => (&digits[..i], digits[i + 1..].parse::<i64>().ok()?),
        None => (digits, 0),
    };
    let (whole, frac) = mantissa.split_once('.').unwrap_or((mantissa, ""));
    let all: String = format!("{whole}{frac}");
    let trimmed = all.trim_start_matches('0');
    let significand = if trimmed.is_empty() { "0" } else { trimmed };
    let places = i64::try_from(frac.len()).ok()?;
    Some((significand.to_string(), exp - places))
}

/// What [`write`] found or did.
#[derive(Clone, Debug, Default)]
pub struct Written {
    /// The files written, or with `check` the files that differ.
    pub files: Vec<String>,
}

/// Write the generated package into `out` and, when given, the LexLean
/// module; with `check`, write nothing and list each file that differs from
/// what the writer would write now.
pub fn write(
    rules: &Path,
    register: &Path,
    out: &Path,
    lexlean: Option<&Path>,
    check: bool,
) -> Result<Written, UorustError> {
    let (rules, _) = read_rules(rules)?;
    let reg = registered(register)?;
    let (files, module) = generate(&rules, &reg);
    let mut targets: Vec<(PathBuf, String)> = files
        .into_iter()
        .map(|(rel, text)| (out.join(rel), text))
        .collect();
    if let Some(l) = lexlean {
        targets.push((l.to_path_buf(), module));
    }
    let mut written = Written::default();
    for (path, text) in targets {
        if check {
            if std::fs::read_to_string(&path).ok().as_deref() != Some(text.as_str()) {
                written.files.push(path.display().to_string());
            }
            continue;
        }
        if let Some(dir) = path.parent() {
            std::fs::create_dir_all(dir).map_err(|e| io(dir, e))?;
        }
        std::fs::write(&path, text).map_err(|e| io(&path, e))?;
        written.files.push(path.display().to_string());
    }
    Ok(written)
}

/// A register file as written: its figures and its site rows' places, read
/// back for the writer (which needs only which figures bound a range).
fn registered(path: &Path) -> Result<Register, UorustError> {
    #[derive(Deserialize)]
    struct Row {
        key: String,
        place: String,
    }
    #[derive(Deserialize)]
    struct File {
        #[serde(default)]
        site: Vec<Row>,
    }
    let figures = read_figures(path)?;
    let text = std::fs::read_to_string(path).map_err(|e| io(path, e))?;
    let value: toml::Value = text.parse().map_err(|e| malformed(path, e))?;
    let mut table = value.as_table().cloned().unwrap_or_default();
    table.retain(|k, _| k == "site");
    let file: File = toml::Value::Table(table)
        .try_into()
        .map_err(|e| malformed(path, e))?;
    let sites = file
        .site
        .into_iter()
        .filter(|r| r.place == Place::RangeBound.name())
        .map(|r| Site {
            key: r.key,
            file: String::new(),
            start: (0, 0),
            end: (0, 0),
            literal: String::new(),
            place: Place::RangeBound,
            stratum: None,
            test: false,
            form: Form::Literal,
            bytes: (0, 0),
        })
        .collect();
    Ok(Register {
        figures,
        sites,
        ..Register::default()
    })
}

/// A site a rewrite could not place, with why.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Refused {
    /// The site's key.
    pub key: String,
    /// Why.
    pub why: String,
}

/// What [`rewrite`] did.
#[derive(Clone, Debug, Default)]
pub struct Rewritten {
    /// Sites replaced by a generated name.
    pub replaced: usize,
    /// Files changed.
    pub files: Vec<String>,
    /// Sites with a figure no rewrite placed, each with its typed reason.
    pub refused: Vec<Refused>,
}

/// Where a rewrite puts a figure, or the name it reaches the generated
/// crate by.
enum Placement {
    /// The text the site is replaced by, or the crate name it uses.
    Name(String),
    /// Why no text can replace it.
    Refused(String),
}

/// The text a site with a figure is replaced by, or why it cannot be.
fn replacement(site: &Site, figure: &Figure, krate: &str) -> Placement {
    if let Some(why) = site.place.refusal() {
        return Placement::Refused(why.to_string());
    }
    if site.literal != figure.value {
        return Placement::Refused(format!(
            "the site writes {} and the figure states {}",
            site.literal, figure.value
        ));
    }
    let call = format!("::{krate}::{}!()", figure.name);
    match site.place {
        Place::ConstGeneric => Placement::Name(format!("{{ {call} }}")),
        Place::RangeBound => match constant_type(figure) {
            Some(_) => Placement::Name(format!("::{krate}::{}", constant_name(&figure.name))),
            None => Placement::Refused(
                "a range bound needs a typed constant, and the figure states no type".to_string(),
            ),
        },
        _ => Placement::Name(call),
    }
}

/// Replace, in one file's text, each site a figure lists by its generated
/// name; the sites already written so are left as they are. `located` are
/// the names whose call reads its own location ([`location_lines`]); `bound`
/// gives the crate name a site's package reaches the generated package by,
/// or why it reaches none. Returns the new text, the number replaced and the
/// refusals.
fn rewrite_text(
    text: &str,
    sites: &[Site],
    listed: &BTreeMap<&str, &Figure>,
    located: &Located,
    bound: &dyn Fn(&Site) -> Placement,
) -> (String, usize, Vec<Refused>) {
    let mut edits: Vec<((usize, usize), String)> = Vec::new();
    let mut refused = Vec::new();
    let (columns, _) = location_lines(text, located);
    // The lines a named reading holds, apart from those only an unknown
    // tracked function may make read.
    let named = match located.calls {
        Some(_) => {
            let named = Located {
                calls: None,
                ..located.clone()
            };
            location_lines(text, &named).0
        }
        None => columns.clone(),
    };
    for s in sites.iter().filter(|s| s.form == Form::Literal) {
        let Some(f) = listed.get(s.key.as_str()) else {
            continue;
        };
        if columns.contains(&s.start.0) {
            let why = match &located.calls {
                Some(unknown) if !named.contains(&s.start.0) => format!(
                    "a call on its line may reach a #[track_caller] function the source does not name ({unknown})"
                ),
                _ => "a call on its line reads its column (column!(), a caller's location, or a macro the figures do not read)"
                    .to_string(),
            };
            refused.push(Refused {
                key: s.key.clone(),
                why,
            });
            continue;
        }
        let krate = match bound(s) {
            Placement::Name(k) => k,
            Placement::Refused(why) => {
                refused.push(Refused {
                    key: s.key.clone(),
                    why,
                });
                continue;
            }
        };
        match replacement(s, f, &krate) {
            Placement::Name(r) => edits.push((s.bytes, r)),
            Placement::Refused(why) => refused.push(Refused {
                key: s.key.clone(),
                why,
            }),
        }
    }
    edits.sort_by_key(|e| std::cmp::Reverse(e.0));
    let mut out = text.to_string();
    let n = edits.len();
    for ((a, b), r) in edits {
        out.replace_range(a..b, &r);
    }
    (out, n, refused)
}

/// The name a site's code reaches the generated package by, or why it
/// reaches none: in edition 2015 a path that starts with `::` names the
/// crate's own root, not an extern crate; a package that does not depend on
/// the generated one where the code is built (product code by a normal
/// dependency, test, bench and example code by a normal or dev one, a build
/// script by a build one) cannot name it; one that binds it under two names
/// there, or binds another crate under its name, would make the name mean
/// two crates or another one.
fn placeable(source: Option<&Source>, site: &Site) -> Placement {
    let Some(source) = source else {
        return Placement::Refused("the file belongs to no package of the workspace".to_string());
    };
    if source.edition == "2015" {
        return Placement::Refused(
            "in edition 2015 `::` names the crate root, not an extern crate".to_string(),
        );
    }
    let kinds: &[&str] = match source.kind.as_str() {
        "build" => &["build"],
        "test" | "bench" | "example" => &["normal", "dev"],
        _ if site.test => &["normal", "dev"],
        _ => &["normal"],
    };
    let names: BTreeSet<&String> = kinds
        .iter()
        .filter_map(|k| source.depends.get(*k))
        .flatten()
        .collect();
    let mut names = names.into_iter();
    match (names.next(), names.next()) {
        (None, _) => Placement::Refused(format!(
            "the package {} does not depend on the generated package where this code is built",
            source.package
        )),
        (Some(a), Some(b)) => Placement::Refused(format!(
            "the package {} binds the generated package as both {a} and {b}",
            source.package
        )),
        (Some(name), None) if source.taken.contains(name) => Placement::Refused(format!(
            "the package {} binds another crate as {name}",
            source.package
        )),
        (Some(name), None) => Placement::Name(name.clone()),
    }
}

/// Whether the formatter's layout `laid` of `text` is the same program: the
/// same tokens once both are read in one [`Layout`], but for a trailing
/// comma the formatter adds or drops where the language reads none (after
/// the last element of a list in brackets or braces, or of a parenthesized
/// list of more than one element, as the Rust reference's grammar of
/// arrays, calls, tuples, patterns, parameters and struct expressions
/// allows). Inside the token tree of any other macro call every comma is
/// the macro's, so there the tokens must be equal. `shadowed` is the names
/// the workspace binds to macros of its own. Tokens say nothing of lines:
/// [`moves_location`] is the check for those.
fn same_program(text: &str, laid: &str, shadowed: &BTreeSet<String>) -> bool {
    let parse = |t: &str| -> Option<Vec<TokenTree>> {
        let mut file = syn::parse_file(t).ok()?;
        visit_mut::VisitMut::visit_file_mut(&mut Layout { shadowed }, &mut file);
        Some(
            quote::ToTokens::to_token_stream(&file)
                .into_iter()
                .collect(),
        )
    };
    fn comma(t: &TokenTree) -> bool {
        matches!(t, TokenTree::Punct(p) if p.as_char() == ',')
    }
    fn trimmed(list: &[TokenTree], delimiter: proc_macro2::Delimiter) -> &[TokenTree] {
        use proc_macro2::Delimiter;
        let Some((last, rest)) = list.split_last() else {
            return list;
        };
        let elements = rest.iter().filter(|t| comma(t)).count() + 1;
        let free = match delimiter {
            Delimiter::Bracket | Delimiter::Brace => true,
            Delimiter::Parenthesis => elements > 1,
            Delimiter::None => false,
        };
        if comma(last) && free {
            rest
        } else {
            list
        }
    }
    /// `strict` inside a macro call's tokens, where every comma counts.
    fn same(a: &[TokenTree], b: &[TokenTree], strict: bool) -> bool {
        a.len() == b.len()
            && a.iter().zip(b).enumerate().all(|(i, (x, y))| match (x, y) {
                (TokenTree::Group(g), TokenTree::Group(h)) => {
                    if g.delimiter() != h.delimiter() {
                        return false;
                    }
                    let inner: Vec<TokenTree> = g.stream().into_iter().collect();
                    let other: Vec<TokenTree> = h.stream().into_iter().collect();
                    let strict = strict
                        || i > 0 && matches!(&a[i - 1], TokenTree::Punct(p) if p.as_char() == '!');
                    if strict {
                        same(&inner, &other, true)
                    } else {
                        same(
                            trimmed(&inner, g.delimiter()),
                            trimmed(&other, h.delimiter()),
                            false,
                        )
                    }
                }
                (TokenTree::Ident(p), TokenTree::Ident(q)) => p == q,
                // `&&` is one operator and `& &` two: the spacing is part
                // of the token.
                (TokenTree::Punct(p), TokenTree::Punct(q)) => {
                    p.as_char() == q.as_char() && p.spacing() == q.spacing()
                }
                (TokenTree::Literal(p), TokenTree::Literal(q)) => p.to_string() == q.to_string(),
                _ => false,
            })
    }
    match (parse(text), parse(laid)) {
        (Some(a), Some(b)) => same(&a, &b, false),
        _ => false,
    }
}

/// Whether a layout moves a line whose value reads its own line or column
/// ([`location_lines`] of the text before the layout): such a line must
/// stand, character for character, at the same line number after it, or
/// `line!()`, `column!()` and a caller's `Location` read another place.
fn moves_location(text: &str, laid: &str, located: &Located) -> bool {
    let (_, reading) = location_lines(text, located);
    let before: Vec<&str> = text.lines().collect();
    let after: Vec<&str> = laid.lines().collect();
    reading
        .iter()
        .any(|l| before.get(l - 1) != after.get(l - 1))
}

/// The standard macro a path names, when it names one the figures know: one
/// segment, or `std`/`core`/`alloc` and the name, and not a name the
/// workspace binds to a macro of its own (`shadowed`).
fn standard_macro(path: &syn::Path, shadowed: &BTreeSet<String>) -> Option<String> {
    let segs: Vec<String> = path.segments.iter().map(|s| s.ident.to_string()).collect();
    let name = match segs.as_slice() {
        [one] => one.clone(),
        [root, name] if ["std", "core", "alloc"].contains(&root.as_str()) => name.clone(),
        _ => return None,
    };
    let known =
        EXPRESSION_MACROS.contains(&name.as_str()) || FORMAT_MACROS.contains(&name.as_str());
    (known && !shadowed.contains(&name)).then_some(name)
}

/// One syntax for the layouts the formatter chooses between that are one
/// program, so that [`same_program`] compares what the compiler reads:
///
/// - A match arm's body or a closure's body (with no stated return type)
///   that is a block holding only a tail expression is that expression. A
///   block with no label, attribute, statement or local adds no scope a
///   value or a drop can tell: a match arm's body and a closure's body are
///   each a temporary scope of their own (the Reference, "Destructors",
///   temporary scopes), so the tail's temporaries are dropped at the same
///   point with the block (edition 2021: they live to the end of the
///   enclosing temporary scope, which is the arm or the body; edition 2024:
///   to the block's end, which is the arm's or the body's end); a temporary
///   whose lifetime is extended is extended through a block's tail as
///   through a match arm; the expected type and the coercion reach the tail
///   as they reach the arm. A standard expression macro in that place (a
///   statement macro with no semicolon) expands to an expression either way.
/// - The arms of a match are separated by commas whether or not a block
///   needs one.
/// - A trailing comma after the last argument of a call or a method call,
///   after a signature's last parameter, or at the end of the arguments of a
///   standard macro of [`standard_macro`] is read as nothing: the call and
///   parameter grammars allow it, and every one of those macros takes an
///   optional trailing comma (`$(,)?` in its rules, or the format-argument
///   grammar of `format_args!`) and expands to the same code without it.
struct Layout<'s> {
    shadowed: &'s BTreeSet<String>,
}

impl Layout<'_> {
    fn tail(&self, body: &syn::Expr) -> Option<syn::Expr> {
        let syn::Expr::Block(b) = body else {
            return None;
        };
        if !b.attrs.is_empty() || b.label.is_some() {
            return None;
        }
        match b.block.stmts.as_slice() {
            // A macro in a block's tail is expanded as statements, so one
            // whose expansion ends in a semicolon gives `()` there and its
            // value as an arm (the semicolon ignored): only a standard
            // macro is known to expand to the same expression in both.
            [syn::Stmt::Expr(syn::Expr::Macro(m), None)] => (m.attrs.is_empty()
                && standard_macro(&m.mac.path, self.shadowed).is_some())
            .then(|| syn::Expr::Macro(m.clone())),
            [syn::Stmt::Expr(e, None)] => Some(e.clone()),
            [syn::Stmt::Macro(m)]
                if m.semi_token.is_none()
                    && m.attrs.is_empty()
                    && standard_macro(&m.mac.path, self.shadowed).is_some() =>
            {
                Some(syn::Expr::Macro(syn::ExprMacro {
                    attrs: Vec::new(),
                    mac: m.mac.clone(),
                }))
            }
            _ => None,
        }
    }
}

impl visit_mut::VisitMut for Layout<'_> {
    fn visit_arm_mut(&mut self, a: &mut syn::Arm) {
        visit_mut::visit_arm_mut(self, a);
        if let Some(e) = self.tail(&a.body) {
            *a.body = e;
        }
    }

    fn visit_expr_match_mut(&mut self, m: &mut syn::ExprMatch) {
        visit_mut::visit_expr_match_mut(self, m);
        let n = m.arms.len();
        for (i, arm) in m.arms.iter_mut().enumerate() {
            arm.comma = (i + 1 < n).then(Default::default);
        }
    }

    fn visit_expr_closure_mut(&mut self, c: &mut syn::ExprClosure) {
        visit_mut::visit_expr_closure_mut(self, c);
        if matches!(c.output, syn::ReturnType::Default) {
            if let Some(e) = self.tail(&c.body) {
                *c.body = e;
            }
        }
    }

    fn visit_expr_call_mut(&mut self, c: &mut syn::ExprCall) {
        visit_mut::visit_expr_call_mut(self, c);
        c.args = std::mem::take(&mut c.args).into_iter().collect();
    }

    fn visit_expr_method_call_mut(&mut self, c: &mut syn::ExprMethodCall) {
        visit_mut::visit_expr_method_call_mut(self, c);
        c.args = std::mem::take(&mut c.args).into_iter().collect();
    }

    fn visit_signature_mut(&mut self, s: &mut syn::Signature) {
        visit_mut::visit_signature_mut(self, s);
        if s.variadic.is_none() {
            s.inputs = std::mem::take(&mut s.inputs).into_iter().collect();
        }
    }

    fn visit_macro_mut(&mut self, m: &mut syn::Macro) {
        if standard_macro(&m.path, self.shadowed).is_some() {
            let mut tokens: Vec<TokenTree> = m.tokens.clone().into_iter().collect();
            if matches!(tokens.last(), Some(TokenTree::Punct(p)) if p.as_char() == ',') {
                tokens.pop();
                m.tokens = tokens.into_iter().collect();
            }
        }
    }
}

/// The workspace formatter's layout of a text, run as `rustfmt` reads
/// standard input from the file's directory (so it finds the workspace's
/// configuration and formats no other file); `None` when it cannot run.
fn formatted(text: &str, dir: &Path, edition: &str) -> Option<String> {
    use std::io::Write as _;
    let mut child = std::process::Command::new("rustfmt")
        .args(["--edition", edition, "--emit", "stdout"])
        .current_dir(dir)
        .stdin(std::process::Stdio::piped())
        .stdout(std::process::Stdio::piped())
        .stderr(std::process::Stdio::null())
        .spawn()
        .ok()?;
    child.stdin.take()?.write_all(text.as_bytes()).ok()?;
    let output = child.wait_with_output().ok()?;
    output
        .status
        .success()
        .then(|| String::from_utf8_lossy(&output.stdout).into_owned())
}

/// Replace every site of the workspace that has a figure by the generated
/// name of its figure, file by file. A file the formatter left as it was is
/// laid out by the formatter again after the replacement, and is written
/// only when its tokens are the replaced text's and no line that reads its
/// own location moved; every other byte of a file stays. A second run finds
/// every placed site written so and changes nothing.
pub fn rewrite(root: &Path, rules: &Path, register: &Path) -> Result<Rewritten, UorustError> {
    let (rules, _) = read_rules(rules)?;
    let figures = read_figures(register)?;
    let loaded = load(root, &rules)?;
    let reg = read_loaded(&loaded, &rules, figures)?;
    let root = loaded.root.clone();
    let of: BTreeMap<&str, &Source> = loaded
        .files
        .iter()
        .map(|(f, _)| (f.rel.as_str(), f))
        .collect();
    let bound = |s: &Site| placeable(of.get(s.file.as_str()).copied(), s);
    let listed = reg.listed();
    let mut by_file: BTreeMap<&str, Vec<Site>> = BTreeMap::new();
    for s in &reg.sites {
        by_file.entry(s.file.as_str()).or_default().push(s.clone());
    }
    let mut done = Rewritten::default();
    for (file, sites) in by_file {
        let path = root.join(file);
        let text = std::fs::read_to_string(&path).map_err(|e| io(&path, e))?;
        let (_, n, refused) = rewrite_text(&text, &sites, &listed, &loaded.located, &bound);
        if n == 0 {
            done.refused.extend(refused);
            continue;
        }
        let dir = path.parent().unwrap_or(&root).to_path_buf();
        let edition = of.get(file).map_or("", |f| f.edition.as_str());
        let clean = formatted(&text, &dir, edition).as_deref() == Some(text.as_str());
        // The layout of the text with the given sites replaced and their
        // number, or why it is not the same program.
        let lay = |chosen: &[Site]| -> (String, usize, Option<&'static str>) {
            let (new, n, _) = rewrite_text(&text, chosen, &listed, &loaded.located, &bound);
            let laid = if clean {
                formatted(&new, &dir, edition).unwrap_or_else(|| new.clone())
            } else {
                new.clone()
            };
            let why = if !same_program(&new, &laid, &loaded.shadowed) {
                Some("the formatter's layout changed the file's tokens")
            } else if moves_location(&new, &laid, &loaded.located) {
                Some("the formatter's layout moves a line that reads its own line or column")
            } else {
                None
            };
            (laid, n, why)
        };
        done.refused.extend(refused);
        let (laid, n) = match lay(&sites) {
            (laid, n, None) => (laid, n),
            // Site by site in source order: each is kept when the layout of
            // the file with it and every site kept before is the same program
            // and moves no line that reads its place, and refused otherwise.
            // The last layout that held is the one written.
            (_, _, Some(_)) => {
                let refused_keys: BTreeSet<String> =
                    done.refused.iter().map(|r| r.key.clone()).collect();
                let mut kept: Vec<Site> = sites
                    .iter()
                    .filter(|s| s.form != Form::Literal || !listed.contains_key(s.key.as_str()))
                    .cloned()
                    .collect();
                let mut last: Option<(String, usize)> = None;
                for s in sites.iter().filter(|s| {
                    s.form == Form::Literal
                        && listed.contains_key(s.key.as_str())
                        && !refused_keys.contains(&s.key)
                }) {
                    kept.push(s.clone());
                    match lay(&kept) {
                        (laid, n, None) => last = Some((laid, n)),
                        (_, _, Some(why)) => {
                            kept.pop();
                            done.refused.push(Refused {
                                key: s.key.clone(),
                                why: why.to_string(),
                            });
                        }
                    }
                }
                match last {
                    Some(laid) if laid.1 > 0 => laid,
                    _ => continue,
                }
            }
        };
        std::fs::write(&path, laid).map_err(|e| io(&path, e))?;
        done.replaced += n;
        done.files.push(file.to_string());
    }
    Ok(done)
}

/// What a gate needs to know of a workspace's figures.
#[derive(Clone, Debug, Default)]
pub struct Checked {
    /// The register's counts, read from the source now.
    pub counts: Counts,
    /// What fails the gate, one line each.
    pub findings: Vec<String>,
}

/// The gate: the register is what [`extract`] would write now, no counted
/// site lacks a figure, every figure states its home (a kind and a non-blank
/// citation), every rewritten site names the figure that lists it, every
/// file is stratified, parses and was read whole, the figures whose home
/// names no check are no more than the rules' declared ceiling (so the gate
/// is not passed by renaming alone), and the generated files (when given)
/// are what [`write`] would write.
pub fn check(
    root: &Path,
    rules_path: &Path,
    register: &Path,
    package: Option<&Path>,
    lexlean: Option<&Path>,
) -> Result<Checked, UorustError> {
    let (rules, digest) = read_rules(rules_path)?;
    let figures = read_figures(register)?;
    let reg = read(root, &rules, figures)?;
    let mut findings = Vec::new();
    let on_disk = std::fs::read_to_string(register).map_err(|e| io(register, e))?;
    if on_disk != reg.render(&digest) {
        findings.push(format!(
            "{} is not the register the source gives now: run uorust figures extract",
            register.display()
        ));
    }
    let listed = reg.listed();
    let names: BTreeSet<&str> = reg.figures.iter().map(|f| f.name.as_str()).collect();
    for s in &reg.sites {
        match (&s.form, listed.get(s.key.as_str())) {
            (Form::Macro(n) | Form::Constant(n), _) if !names.contains(n.as_str()) => findings
                .push(format!(
                    "{} {}:{}: names the figure {n}, which the register does not state",
                    s.key, s.file, s.start.0
                )),
            // The source is what the program uses: a site written as one
            // figure's name and listed by another is listed wrongly.
            (Form::Macro(n) | Form::Constant(n), Some(f)) if f.name != *n => {
                findings.push(format!(
                    "{} {}:{}: names the figure {n}, and the register lists it under {}",
                    s.key, s.file, s.start.0, f.name
                ))
            }
            (_, None) => findings.push(format!(
                "{} {}:{}: the literal {} has no figure",
                s.key, s.file, s.start.0, s.literal
            )),
            _ => {}
        }
        if let Some(f) = listed.get(s.key.as_str()) {
            if s.literal != f.value {
                findings.push(format!(
                    "{}: the site writes {} and the figure {} states {}",
                    s.key, s.literal, f.name, f.value
                ));
            }
        }
    }
    for f in &reg.figures {
        if !homed(f) {
            findings.push(format!("the figure {} states no home", f.name));
        }
    }
    let unchecked: Vec<&str> = reg
        .figures
        .iter()
        .filter(|f| !checked(f))
        .map(|f| f.name.as_str())
        .collect();
    if unchecked.len() > rules.unchecked_ceiling {
        findings.push(format!(
            "{} figures name no check, above the ceiling of {} the rules declare: {}",
            unchecked.len(),
            rules.unchecked_ceiling,
            unchecked.join(", ")
        ));
    }
    for u in &reg.unread {
        findings.push(format!("{u}: not read for sites"));
    }
    for f in &reg.unstratified {
        findings.push(format!("{f}: no stratum names it"));
    }
    for f in &reg.unparsed {
        findings.push(format!("{f}: does not parse"));
    }
    if let Some(out) = package {
        let w = write(rules_path, register, out, lexlean, true)?;
        for f in w.files {
            findings.push(format!("{f} is not what uorust figures write writes now"));
        }
    }
    Ok(Checked {
        counts: reg.counts(),
        findings,
    })
}

