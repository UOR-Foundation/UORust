    /// The sites of a one-file workspace, with the names the file binds that
    /// may stand for a macro, as [`load`] reads them.
    fn figures_repair_places(text: &str) -> Vec<(String, &'static str)> {
        let mut shadowed = BTreeSet::new();
        let tree = syn::parse_file(text).expect("parses");
        if bound_macro_names(&tree, &["p".to_string()].into(), &mut shadowed)
            && without_prelude(&tree)
        {
            every_standard_name(&mut shadowed);
        }
        figures_sites_with(text, &BTreeMap::new(), &shadowed)
            .into_iter()
            .map(|s| (s.literal, s.place.name()))
            .collect()
    }

    fn figures_repair_pairs(pairs: &[(&str, &'static str)]) -> Vec<(String, &'static str)> {
        pairs.iter().map(|(l, p)| (l.to_string(), *p)).collect()
    }

    /// A scratch workspace of the given files (paths relative to its root).
    fn figures_repair_workspace(tag: &str, files: &[(&str, &str)]) -> PathBuf {
        let dir = std::env::temp_dir().join(format!(
            "uorust-figures-repair-{tag}-{}",
            std::process::id()
        ));
        let _ = std::fs::remove_dir_all(&dir);
        for (rel, text) in files {
            let path = dir.join(rel);
            std::fs::create_dir_all(crate::ingest::parent(&path)).expect("a scratch directory");
            std::fs::write(&path, text).expect("written");
        }
        dir
    }

