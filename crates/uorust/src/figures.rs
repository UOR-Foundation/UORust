/// The built-in attributes that are macros of the standard prelude, not
/// inert attributes (the Reference, "Built-in attributes index" and the
/// prelude `core::prelude::v1`): a name the workspace binds (a `use`, a glob
/// of another crate, a `#[proc_macro_attribute]` or `#[proc_macro_derive]`
/// of its own) takes precedence over the prelude, so under such a binding
/// the attribute is the workspace's macro. An inert built-in attribute
/// (`cfg`, `inline`, `repr`, ...) cannot be shadowed: rustc refuses the
/// ambiguity.
const SHADOWABLE_ATTRIBUTES: [&str; 7] = [
    "test",
    "bench",
    "derive",
    "global_allocator",
    "test_case",
    "cfg_accessible",
    "cfg_eval",
];

/// Whether a derive path names a standard derive: one segment that the
/// workspace binds to nothing of its own, or a path from `std` or `core`
/// (which the workspace does not rebind) ending in a standard derive's name.
fn standard_derive(p: &syn::Path, shadowed: &BTreeSet<String>) -> bool {
    let segs: Vec<String> = p.segments.iter().map(|s| s.ident.to_string()).collect();
    let Some(last) = segs.last() else {
        return false;
    };
    let named = STANDARD_DERIVES.contains(&last.as_str());
    let reached = match segs.as_slice() {
        [one] => p.leading_colon.is_none() && !shadowed.contains(one),
        [root, _, ..] => ["std", "core"].contains(&root.as_str()) && !shadowed.contains(root),
        [] => false,
    };
    named && reached
}

/// Whether an attribute is one the language defines, not a macro: an inert
/// built-in one, a built-in macro the workspace does not shadow (a `derive`
/// of the standard derives only), a `cfg_attr` whose attributes are built
/// in, or an inert tool attribute. `shadowed` is every name the workspace
/// binds that could stand for a macro.
fn builtin(meta: &syn::Meta, shadowed: &BTreeSet<String>) -> bool {
    use syn::parse::Parser;
    let path = meta.path();
    if path.leading_colon.is_some() {
        return false;
    }
    let segs: Vec<String> = path.segments.iter().map(|s| s.ident.to_string()).collect();
    let free = |name: &str| !SHADOWABLE_ATTRIBUTES.contains(&name) || !shadowed.contains(name);
    match segs.as_slice() {
        [tool, _, ..] => {
            ["rustfmt", "clippy", "diagnostic"].contains(&tool.as_str()) && !shadowed.contains(tool)
        }
        [name] if name == "derive" => {
            free(name)
                && match meta {
                    syn::Meta::List(l) => Punctuated::<syn::Path, syn::Token![,]>::parse_terminated
                        .parse2(l.tokens.clone())
                        .is_ok_and(|ps| ps.iter().all(|p| standard_derive(p, shadowed))),
                    _ => false,
                }
        }
        [name] if name == "cfg_attr" => match meta {
            syn::Meta::List(l) => Punctuated::<syn::Meta, syn::Token![,]>::parse_terminated
                .parse2(l.tokens.clone())
                .is_ok_and(|ms| ms.iter().skip(1).all(|m| builtin(m, shadowed))),
            _ => false,
        },
        [name] => BUILTIN_ATTRIBUTES.contains(&name.as_str()) && free(name),
        [] => false,
    }
}

/// The rule file: what the caller decides about a workspace's literals.
#[derive(Clone, Debug, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Rules {
    /// [`RULES_SPEC`].
    pub spec: String,
    /// The generated package.
    pub package: GeneratedPackage,
    /// Literal values never counted, written as Rust literals (`"0"`,
    /// `"1"`): a site is exempt when its value equals one of them.
    #[serde(default)]
    pub exempt: Vec<String>,
    /// Whether literals of test code (a `#[cfg(test)]` item, a test target,
    /// a file only test code declares) are counted.
    pub count_tests: bool,
    /// The strata, by path prefix relative to the workspace root; a file
    /// belongs to the stratum of its longest matching prefix.
    #[serde(default)]
    pub stratum: Vec<Stratum>,
    /// How many figures may have a home that names no check before the
    /// gate fails: a declared parameter of the workspace's policy, 0 when
    /// the rule file declares none, so that a home is never reached by
    /// renaming alone unless the policy says how far.
    #[serde(default)]
    pub unchecked_ceiling: usize,
}

